    board_fresh: bool,
    /// Per-sub-circuit anchors for the Push modal's explicit seeding selection
    /// (`seed.groups`/`seed.all`): where each group's main IC already sits on the
    /// board, so `seedSelectedGroups` can centre the group's saved layout there.
    group_anchors: *const std.StringHashMapUnmanaged(GroupAnchor),
    /// Exact saved row selected by the PCB editor for an authoritative push.
    /// When set, matched parts may move and the saved copper/outline replaces
    /// KiCad's corresponding layout geometry.
    authoritative_layout: ?KicadPushLayout = null,
};

/// Walk every board fp that didn't match any design instance and emit the
/// appropriate orphan-handling op: `remove` when --prune is on, otherwise an
/// informational `flag_stale`. The sync deliberately does NOT lock stale
/// footprints — footprint locking is left entirely to the user in KiCad, so a
/// sync never flips the padlock on (or off) a part.
fn emitStaleOps(
    parsed: ParsedSyncPlan,
    matched_uuids: *std.StringHashMapUnmanaged(void),
    w: anytype,
    first_op: *bool,
    summary: *SyncSummary,
) !void {
    for (parsed.board) |bfp| {
        // Ordinary sync leaves an unrelated manual KiCad footprint alone. The
        // explicit authoritative handoff mirrors the design and therefore
        // prunes an unmatched footprint even when it predates canopy_uuid.
        if (bfp.uuid.len == 0 and parsed.seed.authoritative_layout_name == null) continue;
        if (matched_uuids.contains(bfp.kicad_uuid)) continue;
        const target = opTargetUuid(bfp);
        if (target.len == 0) continue;
        if (parsed.prune_stale) {
            try emitOp(w, first_op, "remove", .{ .{ "uuid", target }, .{ "ref", bfp.ref } });
            summary.removed += 1;
            continue;
        }
        try emitOp(w, first_op, "flag_stale", .{ .{ "uuid", target }, .{ "ref", bfp.ref } });
        summary.flagged_stale += 1;
    }
}

/// Treat a board footprint's name as matching the design's short name when
/// it equals either the short name itself or the canonical KiCad name
/// declared inside `lib/footprints/<short>.sexp`. Legacy boards routinely
/// carry the KiCad-canonical name (`C_0201_0603Metric`) because they were
/// laid out from a `kicad-cli`-exported netlist — without this aliasing
/// every such fp would emit a spurious swap_footprint on the first sync.
fn footprintNameMatches(d: *DiffContext, board_name: []const u8, short: []const u8) bool {
    // Strip the `<lib>:` prefix older sync clients attached to every
    // footprint it created (`eda-sync:c-0201`). KiCad's own footprints
    // also carry a library nickname in the same form (`Capacitor_SMD:…`),
    // and the design-side `short` is always library-bare.
    const board_bare = stripLibPrefix(board_name);
    if (std.mem.eql(u8, board_bare, short)) return true;
    const canonical = canonicalFootprintName(d, short) orelse return false;
    return std.mem.eql(u8, board_bare, canonical);
}

/// Resolve the KiCad-canonical name for `short` ("c-0201" → "C_0201_0603Metric"),
/// cached per-request. Returns null when the .sexp file is missing or
/// doesn't parse as a footprint form.
fn canonicalFootprintName(d: *DiffContext, short: []const u8) ?[]const u8 {
    return canonicalFootprintNameImpl(d, short) catch null;
}

fn canonicalFootprintNameImpl(d: *DiffContext, short: []const u8) !?[]const u8 {
    if (d.canonical_fp_name.get(short)) |cached| {
        if (cached.len == 0) return null;
        return cached;
    }
    const fp_path = try std.fmt.allocPrint(d.spc.arena, path_fmt_fp_sexp, .{ d.spc.project_dir, short });
    const fp_source = infra_fs.cwd().readFileAlloc(d.spc.arena, fp_path, lib_limits.max_footprint_bytes) catch {
        try d.canonical_fp_name.put(d.spc.arena, short, "");
        return null;
    };
    const name = netlist_mod.extractFootprintName(d.spc.arena, fp_source) catch {
        try d.canonical_fp_name.put(d.spc.arena, short, "");
        return null;
    };
    try d.canonical_fp_name.put(d.spc.arena, short, name);
    return name;
}

/// Extract the parent-path prefix of a hierarchical ref-des. Returns the
/// empty string for a top-level ref. e.g. `"adc1/C146"` → `"adc1/"`,
/// `"C18"` → `""`.
fn parentPathOf(ref: []const u8) []const u8 {
    if (std.mem.lastIndexOfScalar(u8, ref, '/')) |i| return ref[0 .. i + 1];
    return "";
}

/// Build the (parent_path, value) key used for migration-mode heuristic
/// matching. We deliberately omit footprint_name: legacy boards routinely
/// carry KiCad-canonical names (`C_0201_0603Metric`) while the design
/// emits EDA-short names (`c-0201`). The swap_footprint op the diff loop
/// emits afterwards handles the rename, and value is specific enough to
/// keep different cap sizes apart within a sub-section.
fn heuristicKey(arena: std.mem.Allocator, parent: []const u8, _: []const u8, value: []const u8) std.mem.Allocator.Error![]const u8 {
    return std.fmt.allocPrint(arena, "{s}|{s}", .{ parent, value });
}

/// Decide which board fp a design instance pairs with, using the two
/// non-heuristic tiers (canopy uuid, then reference). Refuses any
/// match — including by_uuid — for a fp that another instance has
/// already claimed in this walk, and refuses by_ref matches whose fp
/// is reserved by some other instance's canopy_uuid. Without those
/// guards, legacy boards (where Reference/canopy_uuid disagree on the
/// same physical fp, or two design instances share a canopy_uuid)
/// produce two design instances both writing to one fp and emit
/// contradictory ops every sync. Pure function; extracted from
/// `matchInstance` so the collision rules are directly testable.
fn pickByUuidOrRef(
    inst_uuid: []const u8,
    inst_ref: []const u8,
    by_uuid: *std.StringHashMapUnmanaged(BoardFp),
    by_ref: *std.StringHashMapUnmanaged(BoardFp),
    reserved_kicad_uuids: *std.StringHashMapUnmanaged(void),
    already_claimed: *std.StringHashMapUnmanaged(void),
) ?BoardFp {
    if (by_uuid.get(inst_uuid)) |m| {
        if (!already_claimed.contains(m.kicad_uuid)) return m;
    }
    if (inst_ref.len > 0) {
        if (by_ref.get(inst_ref)) |m| {
            if (!reserved_kicad_uuids.contains(m.kicad_uuid) and
                !already_claimed.contains(m.kicad_uuid))
            {
                return m;
            }
        }
    }
    return null;
}

/// Adopt-in-place fallback: a board fp whose KiCad-internal uuid equals the
/// design instance's canopy_uuid. That equality only arises for footprints
/// the add path created (it stamps KiCad uuid := canopy_uuid), so this link
/// survives even after the canopy_uuid *property* is stripped (a swap that
/// didn't reissue it, a pcbnew round-trip). KiCad uuids are random and canopy
/// uuids are SHA-derived, so a coincidental cross-match is impossible — this
/// strictly recovers our own orphans. Refuses an fp another instance already
/// claimed in this walk. Pure; extracted from `matchInstance` to be testable.
fn pickByKicadUuid(
    inst_uuid: []const u8,
    by_kicad_uuid: *std.StringHashMapUnmanaged(BoardFp),
    already_claimed: *std.StringHashMapUnmanaged(void),
) ?BoardFp {
    if (by_kicad_uuid.get(inst_uuid)) |m| {
        if (!already_claimed.contains(m.kicad_uuid)) return m;
    }
    return null;
}

fn matchInstance(d: *DiffContext, inst: export_kicad.FlatInstance) ?BoardFp {
    // Net-signature relink wins over canopy uuid: the relink builder
    // only populates a pairing when there's an orphan board fp with the
    // same wiring + footprint AND no other claimant. When that fires
    // for a design instance whose canopy uuid happens to also point at
    // a (likely sync-created duplicate at origin) by_uuid entry, the
    // netsig pair wins and the duplicate falls into stale — exactly
    // what the user wants to recover a board where a hierarchy move
    // (top-level `Q1` → `disp/Q3`) caused the sync to create a clone
    // instead of relinking the existing fp.
    if (d.migrate_heuristic) {
        if (d.by_netsig.get(inst.uuid)) |m| {
            if (!d.matched_uuids.contains(m.kicad_uuid)) return m;
        }
    }
    if (pickByUuidOrRef(inst.uuid, inst.ref_des, d.by_uuid, d.by_ref, d.reserved_kicad_uuids, d.matched_uuids)) |m| return m;
    // Adopt-in-place: a board fp whose KiCad-internal uuid equals this
    // instance's canopy_uuid — a self-stamped orphan whose canopy_uuid
    // property was stripped (a swap that didn't reissue it, a pcbnew
    // round-trip). Preserves the user's placement instead of adding a
    // duplicate at the origin. handleMatched re-stamps canopy_uuid for
    // every match tier (Option G), so this tier emits nothing itself.
    if (pickByKicadUuid(inst.uuid, d.by_kicad_uuid, d.matched_uuids)) |m| return m;
    // Migration tier (parent_path/value). canopy_uuid stamping + ref-des
    // rename are emitted by handleMatched for every match tier (Option G),
    // so matchInstance no longer emits anything itself. Refuse an fp some
    // earlier instance already claimed this walk — falling through to an
    // add is strictly better than two instances emitting contradictory
    // ops against one footprint.
    if (heuristicMatch(d, inst)) |m| {
        if (!d.matched_uuids.contains(m.kicad_uuid)) return m;
    }
    return null;
}

/// Migration-mode lookup for (parent_path, value) pairings. Gated on
/// --migrate. Net-signature relink is checked separately in
/// `matchInstance` (it must beat by_uuid to recover from sync-created
/// duplicates) so it lives outside this helper.
fn heuristicMatch(d: *DiffContext, inst: export_kicad.FlatInstance) ?BoardFp {
    if (!d.migrate_heuristic) return null;
    return d.by_migration.get(inst.uuid);
}

/// Build a sortable signature string of a design instance's pad-net
/// assignments, derived from the diff loop's `pad_net_map`. Format is
/// `<pad1>=<net1>;<pad2>=<net2>;…` with pads sorted lexicographically so
/// two instances with identical wiring produce identical strings.
/// Returns "" when the instance has no pads on named nets (NC-only),
/// signalling the caller to skip it for relinking.
fn designInstanceNetSig(
    arena: std.mem.Allocator,
    inst_ref_des: []const u8,
    pad_net_map: *std.StringHashMapUnmanaged([]const u8),
) ![]const u8 {
    var pairs: std.ArrayList(struct { pad: []const u8, net: []const u8 }) = .empty;
    var it = pad_net_map.iterator();
    while (it.next()) |entry| {
        const key = entry.key_ptr.*;
        const sep = std.mem.indexOfScalar(u8, key, '|') orelse continue;
        if (!std.mem.eql(u8, key[0..sep], inst_ref_des)) continue;
        try pairs.append(arena, .{ .pad = key[sep + 1 ..], .net = entry.value_ptr.* });
    }
    if (pairs.items.len == 0) return "";
    std.mem.sort(@TypeOf(pairs.items[0]), pairs.items, {}, struct {
        fn lessThan(_: void, a: @TypeOf(pairs.items[0]), b: @TypeOf(pairs.items[0])) bool {
            return std.mem.lessThan(u8, a.pad, b.pad);
        }
    }.lessThan);
    var buf: std.Io.Writer.Allocating = .init(arena);
    const w = &buf.writer;
    for (pairs.items) |p| try w.print("{s}={s};", .{ p.pad, p.net });
    return buf.written();
}

/// Same signature format as `designInstanceNetSig`, computed from the
/// pad list the reader captured for a board fp. Empty when the fp has no
/// pads on named nets.
fn boardFpNetSig(arena: std.mem.Allocator, bfp: BoardFp) ![]const u8 {
    var pairs: std.ArrayList(struct { pad: []const u8, net: []const u8 }) = .empty;
    for (bfp.pads) |p| {
        if (p.net.len == 0) continue;
        try pairs.append(arena, .{ .pad = p.number, .net = p.net });
    }
    if (pairs.items.len == 0) return "";
    std.mem.sort(@TypeOf(pairs.items[0]), pairs.items, {}, struct {
        fn lessThan(_: void, a: @TypeOf(pairs.items[0]), b: @TypeOf(pairs.items[0])) bool {
            return std.mem.lessThan(u8, a.pad, b.pad);
        }
    }.lessThan);
    var buf: std.Io.Writer.Allocating = .init(arena);
    const w = &buf.writer;
    for (pairs.items) |p| try w.print("{s}={s};", .{ p.pad, p.net });
    return buf.written();
}

/// Pair orphan board fps with orphan design instances by exact net
/// signature. "Orphan" = won't pair via canopy_uuid match, ref-des
/// match, or the (parent_path, value) migration tier. Only emits a pair
/// when the signature is unique on BOTH sides — if two board fps have
/// the same signature, or two design instances do, we skip both rather
/// than guess. The footprint name must also match (canonical or short).
///
/// Output keyed by design instance uuid so heuristicMatch resolves in O(1).
fn buildNetSignatureRelinkIndex(
    arena: std.mem.Allocator,
    project_dir: []const u8,
    board: []const BoardFp,
    instances: []const export_kicad.FlatInstance,
    by_uuid: *std.StringHashMapUnmanaged(BoardFp),
    _: *std.StringHashMapUnmanaged(BoardFp), // by_ref — unused since the netsig tier
    // deliberately considers insts that already match by_ref so it can
    // pair them with an orphan instead of a sync-created duplicate.
    by_migration: *std.StringHashMapUnmanaged(BoardFp),
    pad_net_map: *std.StringHashMapUnmanaged([]const u8),
    out: *std.StringHashMapUnmanaged(BoardFp),
) !void {
    // The migration index is keyed by design uuid → BoardFp; mark which
    // board fps it already claimed so we don't double-pair them.
    var migration_claimed_kids = std.StringHashMapUnmanaged(void).empty;
    var mit = by_migration.iterator();
    while (mit.next()) |entry| {
        const m = entry.value_ptr.*;
        if (m.kicad_uuid.len > 0) try migration_claimed_kids.put(arena, m.kicad_uuid, {});
    }

    // Bucket orphan board fps by netsig (with footprint name appended so
    // a stray `c-0201`-vs-`r-0201` collision on pads can't pair).
    var board_by_sig = std.StringHashMapUnmanaged(std.ArrayList(BoardFp)).empty;
    for (board) |bfp| {
        if (bfp.uuid.len == 0) continue;
        if (migration_claimed_kids.contains(bfp.kicad_uuid)) continue;
        // Skip board fps whose canopy uuid already pairs with a design
        // instance directly — those are reachable via by_uuid and not
        // orphans at all.
        if (by_uuid.contains(bfp.uuid) and matchesUuidExactlyInDesign(bfp.uuid, instances)) continue;
        const sig = try boardFpNetSig(arena, bfp);
        if (sig.len == 0) continue;
        const key = try std.fmt.allocPrint(arena, "{s}|{s}", .{ bfp.footprint_name, sig });
        const e = try board_by_sig.getOrPut(arena, key);
        if (!e.found_existing) e.value_ptr.* = .empty;
        try e.value_ptr.append(arena, bfp);
    }

    // Bucket design instances by netsig. We don't skip insts that match
    // by_uuid or by_ref — those matches may be to a sync-created
    // duplicate at the origin (same canopy_uuid AND same ref-des as the
    // design instance because the previous sync created it from the
    // design state, but at the wrong physical location). Letting netsig
    // consider this instance lets it pair with the genuine orphan
    // board fp instead, dropping the duplicate into stale.
    //
    // Migration-tier matches are already a deterministic pairing so we
    // skip those — netsig overriding them would just churn.
    var design_by_sig = std.StringHashMapUnmanaged(std.ArrayList(export_kicad.FlatInstance)).empty;
    // We don't skip ANY insts (not by_uuid, by_ref, or by_migration) so
    // netsig can override every other tier when it finds a unique
    // matching orphan. The pair only fires when the signature is unique
    // on both sides — if migration's pair is a legit physical match
    // they'd share the signature with the orphan and the resulting
    // ambiguity (2 board fps, 1 design inst) skips the pair.
    for (instances) |inst| {
        const sig = try designInstanceNetSig(arena, inst.ref_des, pad_net_map);
        if (sig.len == 0) continue;
        const fp_short = stripLibPrefix(inst.footprint);
        const key = try std.fmt.allocPrint(arena, "{s}|{s}", .{ fp_short, sig });
        const e = try design_by_sig.getOrPut(arena, key);
        if (!e.found_existing) e.value_ptr.* = .empty;
        try e.value_ptr.append(arena, inst);
    }

    // For each design signature with exactly one orphan instance AND
    // exactly one orphan board fp on the same signature, pair them.
    // Footprint-name in the key uses the EDA short name for the design
    // side and the KiCad-canonical name for the board side. We compare
    // by trying both forms when looking up — if the board's canonical
    // form maps back to the same short name, the signatures match.
    var dit = design_by_sig.iterator();
    while (dit.next()) |entry| {
        if (entry.value_ptr.items.len != 1) continue;
        const inst = entry.value_ptr.items[0];
        const sig_after_pipe = std.mem.indexOfScalar(u8, entry.key_ptr.*, '|') orelse continue;
        const sig = entry.key_ptr.*[sig_after_pipe + 1 ..];

        // Try matching the board side first by EDA short name (same key),
        // then by walking all board buckets whose sig matches and whose
        // footprint name canonicalises to the same short form.
        var found_board: ?BoardFp = null;
        var ambiguous = false;
        if (board_by_sig.get(entry.key_ptr.*)) |bucket| {
            if (bucket.items.len == 1) found_board = bucket.items[0];
            if (bucket.items.len > 1) ambiguous = true;
        }
        if (found_board == null and !ambiguous) {
            // Fall back: scan all board buckets, accepting any whose
            // signature suffix matches and whose footprint name is the
            // KiCad-canonical alias of the design's short name.
            const fp_short = stripLibPrefix(inst.footprint);
            var bit = board_by_sig.iterator();
            while (bit.next()) |bentry| {
                const bkey = bentry.key_ptr.*;
                const bsep = std.mem.indexOfScalar(u8, bkey, '|') orelse continue;
                if (!std.mem.eql(u8, bkey[bsep + 1 ..], sig)) continue;
                const board_fp_name = bkey[0..bsep];
                if (!std.mem.eql(u8, board_fp_name, fp_short) and
                    !boardFpNameAliasesShort(arena, project_dir, board_fp_name, fp_short))
                    continue;
                if (bentry.value_ptr.items.len != 1) {
                    ambiguous = true;
                    break;
                }
                if (found_board != null) {
                    ambiguous = true;
                    break;
                }
                found_board = bentry.value_ptr.items[0];
            }
        }
        if (ambiguous) continue;
        const board_fp = found_board orelse continue;
        try out.put(arena, inst.uuid, board_fp);
    }
}

/// Return true when at least one design instance carries `uuid` as its
/// canopy uuid — used by net-signature relink to skip board fps that
/// already pair through the by_uuid index.
fn matchesUuidExactlyInDesign(uuid: []const u8, instances: []const export_kicad.FlatInstance) bool {
    for (instances) |inst| {
        if (std.mem.eql(u8, inst.uuid, uuid)) return true;
    }
    return false;
}

/// True when `board_name` is the KiCad-canonical alias of EDA short name
/// `short` (e.g. `C_0201_0603Metric` ↔ `c-0201`). Reads
/// `lib/footprints/<short>.sexp` on demand; failures degrade to false so
/// a missing library doesn't pair the wrong fp.
fn boardFpNameAliasesShort(arena: std.mem.Allocator, project_dir: []const u8, board_name: []const u8, short: []const u8) bool {
    if (std.mem.eql(u8, board_name, short)) return true;
    // Re-read the .sexp on demand — this is called during relink-index
    // construction (once per sync), not per-instance in the diff loop,
    // so the cost is fine.
    const fp_path = std.fmt.allocPrint(arena, path_fmt_fp_sexp, .{ project_dir, short }) catch return false;
    const fp_source = infra_fs.cwd().readFileAlloc(arena, fp_path, lib_limits.max_footprint_bytes) catch return false;
    const canonical = netlist_mod.extractFootprintName(arena, fp_source) catch return false;
    return std.mem.eql(u8, board_name, canonical);
}

/// Pair board footprints with design instances by (parent_path,
/// footprint_name, value). When a key has the same count N on both sides,
/// pair them deterministically — sort each side by ref-des and match
/// element-i to element-i. The N==M skip rule prevents a 12-cap section
/// from silently absorbing 8 caps and dropping 4 on the floor.
///
/// The pairings populate `out` keyed by design instance uuid so the diff
/// loop can resolve each `inst.uuid` → adopted `BoardFp` in O(1).
fn buildMigrationIndex(
    arena: std.mem.Allocator,
    board: []const BoardFp,
    instances: []const export_kicad.FlatInstance,
    out: *std.StringHashMapUnmanaged(BoardFp),
) !void {
    // Index design + board by heuristic key. Hash → list of refs; we sort
    // the lists later for deterministic pairing.
    var board_groups = std.StringHashMapUnmanaged(std.ArrayList(BoardFp)).empty;
    var design_groups = std.StringHashMapUnmanaged(std.ArrayList(export_kicad.FlatInstance)).empty;

    for (board) |bfp| {
        const key = try heuristicKey(arena, parentPathOf(bfp.ref), bfp.footprint_name, bfp.value);
        const e = try board_groups.getOrPut(arena, key);
        if (!e.found_existing) e.value_ptr.* = .empty;
        try e.value_ptr.append(arena, bfp);
    }
    for (instances) |inst| {
        const fp_name = stripLibPrefix(inst.footprint);
        const key = try heuristicKey(arena, parentPathOf(inst.ref_des), fp_name, inst.value);
        const e = try design_groups.getOrPut(arena, key);
        if (!e.found_existing) e.value_ptr.* = .empty;
        try e.value_ptr.append(arena, inst);
    }

    var it = design_groups.iterator();
    while (it.next()) |entry| {
        const dgroup = entry.value_ptr.*;
        const bgroup = board_groups.get(entry.key_ptr.*) orelse continue;
        if (dgroup.items.len != bgroup.items.len) continue;
        // Sort both sides by ref-des so the pairing is stable across
        // re-runs and across rebuilds. Different runs of --migrate against
        // the same inputs MUST produce the same plan.
        std.mem.sort(BoardFp, bgroup.items, {}, lessByRef);
        std.mem.sort(export_kicad.FlatInstance, dgroup.items, {}, lessByDesignRef);
        for (dgroup.items, bgroup.items) |inst, bfp| {
            try out.put(arena, inst.uuid, bfp);
        }
    }
}

fn lessByRef(_: void, a: BoardFp, b: BoardFp) bool {
    return std.mem.lessThan(u8, a.ref, b.ref);
}

fn lessByDesignRef(_: void, a: export_kicad.FlatInstance, b: export_kicad.FlatInstance) bool {
    return std.mem.lessThan(u8, a.ref_des, b.ref_des);
}

/// Per-matched-footprint op tally, split by whether the op changes the board
/// the user sees. `material` = value edits, footprint swaps, pad-net rewires
/// (a real change → counts as `updated`). `meta` = refdes renames and
/// canopy_*/BOM-field stamps ("nothing moves" → counts as `relabeled`, not an
/// update). A footprint with any material op is `updated`; one with only meta
/// ops is `relabeled`. See SyncSummary.relabeled.
const MatchCounts = struct {
    material: u32 = 0,
    meta: u32 = 0,
};

/// Emit (or withhold) the footprint-geometry swap for one matched part;
/// returns 1 when a material swap op landed, else 0. A swap is wanted when
/// the board footprint's name doesn't resolve to the design's (`geometry`),
/// when `?refresh=1` re-bakes every matched part (`refresh`), or when the
/// part's 3D-model orientation drifted from `model-config.json` (`model` —
/// the 3D-alignment workflow: realign in the viewer → Save → next push
/// re-bakes just the drifted parts). `swapFootprint` preserves
/// at/uuid/layer/locked + custom properties and re-applies pad nets, so a
/// swap never moves the part — but it DOES replace the pad geometry with the
/// design library's land pattern. In no-swap mode (`?no_swap=1`) every wanted
/// swap is therefore withheld and tallied in `summary.swaps_suppressed`
/// instead: matched footprints keep their existing (often hand-tuned) board
/// lands while field and pad-net ops flow unchanged. The reason tag lets the
/// preview modal file the row under "Footprint updates" vs "3D model updates".
fn emitSwapForMatch(
    d: *DiffContext,
    inst: export_kicad.FlatInstance,
    m: BoardFp,
    fp_name_short: []const u8,
    w: anytype,
    first: *bool,
) !u32 {
    const geometry = !footprintNameMatches(d, m.footprint_name, fp_name_short);
    const rebake = !geometry and
        (d.swap == .refresh_all or modelDrifted(d, inst, m, fp_name_short));
    if (!geometry and !rebake) return 0;
    // Loaded before the no-swap gate so the suppressed tally counts exactly
    // the swaps a default sync would have planned (a missing lib footprint
    // never emits — and so never suppresses — anything).
    const kmod = loadKicadMod(d.spc, fp_name_short, inst.component) orelse return 0;
    if (d.swap == .none) {
        d.summary.swaps_suppressed += 1;
        return 0;
    }
    const reason = if (geometry)
        swap_reason_geometry
    else if (d.swap == .refresh_all)
        swap_reason_refresh
    else
        swap_reason_model;
    const target = opTargetUuid(m);
    try emitSwapOp(w, first, target, fp_name_short, kmod, inst.ref_des, d.pad_net_map, reason);
    d.summary.swapped += 1;
    return 1;
}

fn handleMatched(
    d: *DiffContext,
    inst: export_kicad.FlatInstance,
    m: BoardFp,
    fp_name_short: []const u8,
    canopy_net: ?[]const u8,
    section: []const u8,
    w: anytype,
    first: *bool,
    counts: *MatchCounts,
) !void {
    // Track matches by KiCad-internal UUID — that field is always
    // populated, whereas canopy_uuid is empty for ref-des-fallback
    // matches until the backfill op lands on a future sync.
    if (m.kicad_uuid.len > 0) try d.matched_uuids.put(d.spc.arena, m.kicad_uuid, {});
    const target = opTargetUuid(m);
    // Deliberately before swap_footprint: the authoritative path forces a
    // geometry refresh, and the writer must see the NEW side/rotation while it
    // adapts front-authored library pads onto the board.
    try emitAuthoritativePose(d, inst.ref_des, m, w, first);
    counts.material += try emitSwapForMatch(d, inst, m, fp_name_short, w, first);
    // The "old" / "ref" keys on set_field ops are display metadata for the
    // preview modal (rename rows read "FB1 → L2", value rows name the part);
    // the file writer ignores keys it doesn't know.
    if (!std.mem.eql(u8, m.ref, inst.ref_des)) {
        try emitOp(w, first, op_set_field, .{
            .{ "uuid", target },
            .{ "field", "reference" },
            .{ "value", inst.ref_des },
            .{ "old", m.ref },
        });
        counts.meta += 1;
    }
    // An empty design value means "no opinion", not "clear it": fixed
    // components (identified by MPN — e.g. every custom part on an
    // import-kicad board) carry no instance value, and blanking the
    // board's human-set Value field would strip its BOM annotations.
    if (inst.value.len > 0 and !std.mem.eql(u8, m.value, inst.value)) {
        try emitOp(w, first, op_set_field, .{
            .{ "uuid", target },
            .{ "field", "value" },
            .{ "value", inst.value },
            .{ "old", m.value },
            .{ "ref", inst.ref_des },
        });
        counts.material += 1;
    }
    // Stamp/realign canopy_uuid whenever it differs from the design's id —
    // this covers BOTH the eager case (a matched fp that has no canopy_uuid
    // yet: by_ref backfill, manual placement, or a migration-tier match) and
    // the drift case (legacy long-form, --migrate pairing). opTargetUuid falls
    // back to kicad_uuid so the writer resolves the fp before canopy_uuid is
    // set. After this op lands, the next sync UUID-matches directly. This is
    // the single stamping point for every match tier (Option G).
    if (!std.mem.eql(u8, m.uuid, inst.uuid)) {
        try emitOp(w, first, op_set_field, .{
            .{ "uuid", target },
            .{ "field", field_canopy_uuid },
            .{ "value", inst.uuid },
            .{ "ref", inst.ref_des },
        });
        counts.meta += 1;
    }
    // Push every design property to KiCad as a custom Field, so adding a
    // new BOM column (manufacturer, datasheet, supplier_pn, …) is a pure
    // server-side change with no client update. Skip property keys that
    // collide with KiCad's built-in ref/value/footprint handling — those
    // travel through dedicated set_field ops above. The canonical-name map
    // upper-cases well-known KiCad field names (mpn → MPN) so manually-
    // placed footprints with the standard column name match cleanly.
    for (inst.properties) |p| {
        if (skipDesignProperty(p.key)) continue;
        if (p.value.len == 0) continue;
        const field_name = canonicalFieldName(p.key);
        const board_value = m.fields.get(field_name) orelse "";
        if (std.mem.eql(u8, board_value, p.value)) continue;
        try emitOp(w, first, op_set_field, .{
            .{ "uuid", target },
            .{ "field", field_name },
            .{ "value", p.value },
            .{ "ref", inst.ref_des },
        });
        counts.meta += 1;
    }
    // Passive routing hint: each pad's intended (device.pin.net) destination,
    // so a layout engineer reading a bare cap/resistor sees what it bridges.
    if (canopy_net) |cn| {
        const board_value = m.fields.get(field_canopy_net) orelse "";
        if (!std.mem.eql(u8, board_value, cn)) {
            try emitOp(w, first, op_set_field, .{
                .{ "uuid", target },
                .{ "field", field_canopy_net },
                .{ "value", cn },
                .{ "ref", inst.ref_des },
            });
            counts.meta += 1;
        }
    }
    // Section provenance: which design `(section …)` this part came from.
    if (section.len > 0) {
        const board_value = m.fields.get(field_canopy_section) orelse "";
        if (!std.mem.eql(u8, board_value, section)) {
            try emitOp(w, first, op_set_field, .{
                .{ "uuid", target },
                .{ "field", field_canopy_section },
                .{ "value", section },
                .{ "ref", inst.ref_des },
            });
            counts.meta += 1;
        }
    }
    counts.material += try emitPadNetOps(d, w, first, target, inst.ref_des, d.pad_net_map, m.pads);
}

/// Emit a pose mutation for a matched footprint when the named PCB-editor
/// layout differs from KiCad. Ordinary sync never reaches this helper with an
/// authoritative layout and therefore retains its no-movement invariant.
fn emitAuthoritativePose(
    d: *DiffContext,
    ref_des: []const u8,
    m: BoardFp,
    w: anytype,
    first: *bool,
) !void {
    const layout = d.authoritative_layout orelse return;
    const pose = layout.poses.get(ref_des) orelse return;
    const back = pose.side == .bottom;
    const kicad_rot = netlispRotToKicad(pose.rot, back);
    const layer = if (back) board_layers.b_cu else board_layers.f_cu;
    if (layout.board_positions) |positions| {
        if (positions.get(m.kicad_uuid)) |old| {
            const drot = @abs(@mod(old.rot - kicad_rot + 180.0, 360.0) - 180.0);
            if (@abs(old.x - pose.x) <= placement_eps_mm and
                @abs(old.y - pose.y) <= placement_eps_mm and
                drot <= placement_eps_deg and std.mem.eql(u8, old.layer, layer)) return;
        }
    }
    if (!first.*) try w.writeAll(",");
    first.* = false;
    try w.writeAll("{\"op\":\"set_footprint_pose\",\"uuid\":");
    try json_writer.writeString(w, opTargetUuid(m));
    try w.writeAll(",\"ref\":");
    try json_writer.writeString(w, ref_des);
    try w.print(",\"x\":{d},\"y\":{d},\"rot\":{d},\"side\":", .{
        mmToNm(pose.x), mmToNm(pose.y), kicad_rot,
    });
    try json_writer.writeString(w, if (back) "bottom" else "top");
    try w.writeAll("}");
    d.summary.layout_parts += 1;
}

/// Property keys we deliberately don't push to KiCad as custom fields:
/// `value`/`footprint` are KiCad-built-in (already handled via dedicated
/// set_field ops on inst.value / inst.footprint), and `description` would
/// collide with the description KiCad reads from the footprint library.
fn skipDesignProperty(key: []const u8) bool {
    if (std.mem.eql(u8, key, "value")) return true;
    if (std.mem.eql(u8, key, form_head_footprint)) return true;
    if (std.mem.eql(u8, key, "description")) return true;
    return false;
}

/// Canonicalise design property keys to KiCad's standard field-column
/// names so users with manually-placed footprints (already carrying
/// "MPN", "Manufacturer", …) don't see a duplicate lower-cased twin land
/// on first sync. Unknown keys pass through unchanged so user-defined
/// property keys still work.
fn canonicalFieldName(key: []const u8) []const u8 {
    if (std.mem.eql(u8, key, "mpn")) return "MPN";
    if (std.mem.eql(u8, key, "manufacturer")) return "Manufacturer";
    if (std.mem.eql(u8, key, "datasheet")) return "Datasheet";
    return key;
}

/// Strip a "subblock/" path prefix from a ref-des — "ldo/U1" → "U1".
fn shortRefLocal(ref: []const u8) []const u8 {
    if (std.mem.lastIndexOfScalar(u8, ref, '/')) |i| return ref[i + 1 ..];
    return ref;
}

/// A passive spoke — R/C/L/F/D prefix. Mirrors render_svg `isHub`: only
/// these carry a meaningful `canopy_net` field (it names the hub pin the
/// spoke bridges to); everything else is a hub and is skipped.
fn isPassiveRef(ref: []const u8) bool {
    const s = shortRefLocal(ref);
    if (s.len == 0) return false;
    return switch (s[0]) {
        'R', 'C', 'L', 'F', 'D' => true,
        else => false,
    };
}

/// A hub — anything that isn't a passive spoke (U/J/P/X/Q ICs/connectors
/// plus any unknown prefix). These are the endpoints a passive's
/// `canopy_net` field points at.
fn isHubRef(ref: []const u8) bool {
    return !isPassiveRef(ref);
}

/// One pad of a passive, with both the display net (collapsed, dedup'd —
/// what set_pad_net assigns) and the full pre-collapse net (used to find
/// the hub pin the pad routes to).
const CanopyPad = struct { pin: []const u8, display: []const u8, full: []const u8 };

fn lessByPadNum(_: void, a: CanopyPad, b: CanopyPad) bool {
    const an = std.fmt.parseInt(u32, a.pin, 10) catch null;
    const bn = std.fmt.parseInt(u32, b.pin, 10) catch null;
    if (an != null and bn != null) return an.? < bn.?;
    return std.mem.lessThan(u8, a.pin, b.pin);
}

/// Build the `canopy_net` field value for one passive: a ` / `-joined,
/// pad-ordered list where each pad reads `<destRef>.<destPin>.<net>` when
/// it sits on exactly one hub pin (e.g. `U8.C3.VDD33USB`), or just `<net>`
/// when the net has zero or many hub pins (e.g. a `GND` rail). Returns null
/// when the passive has no connected pads.
fn buildCanopyNetValue(
    arena: std.mem.Allocator,
    ref_des: []const u8,
    pad_net_map: *std.StringHashMapUnmanaged([]const u8),
    pad_full_net: *std.StringHashMapUnmanaged([]const u8),
    net_hub_pins: *std.StringHashMapUnmanaged(std.ArrayList(export_kicad.FlatPin)),
) !?[]const u8 {
    var pads: std.ArrayList(CanopyPad) = .empty;
    var it = pad_net_map.iterator();
    while (it.next()) |entry| {
        const k = entry.key_ptr.*;
        const sep = std.mem.indexOfScalar(u8, k, '|') orelse continue;
        if (!std.mem.eql(u8, k[0..sep], ref_des)) continue;
        const full = pad_full_net.get(k) orelse entry.value_ptr.*;
        try pads.append(arena, .{ .pin = k[sep + 1 ..], .display = entry.value_ptr.*, .full = full });
    }
    if (pads.items.len == 0) return null;
    std.mem.sort(CanopyPad, pads.items, {}, lessByPadNum);

    var buf: std.Io.Writer.Allocating = .init(arena);
    const w = &buf.writer;
    for (pads.items, 0..) |p, i| {
        if (i > 0) try w.writeAll(" / ");
        // Count the hub pins on this pad's full net (excluding the passive
        // itself). Exactly one → name that device pin; otherwise the net
        // alone, since a rail with many pins has no single target.
        var ep: ?export_kicad.FlatPin = null;
        var count: u32 = 0;
        if (net_hub_pins.get(p.full)) |hubs| {
            for (hubs.items) |hp| {
                if (std.mem.eql(u8, hp.ref_des, ref_des)) continue;
                count += 1;
                if (ep == null) ep = hp;
            }
        }
        if (count == 1) {
            try w.print("{s}.{s}.{s}", .{ shortRefLocal(ep.?.ref_des), ep.?.pin, p.display });
        } else {
            try w.writeAll(p.display);
        }
    }
    return buf.written();
}

/// Float tolerance for comparing on-board model offset/rotation (mm / deg)
/// against the desired values — KiCad stores them at 4 decimals, so anything
/// under a milli-unit is "equal".
const model_drift_eps: f64 = 1e-3;

/// True when board footprint `m`'s 3D-model orientation no longer matches what
/// `model-config.json` specifies for `fp_name_short` — i.e. the user realigned
/// the model in the viewer and a normal push should re-bake just this part.
///
/// Only the offset/rotation (the alignment) is compared, and only when the
/// design actually resolves a model for the footprint; a name-only difference
/// or a board model the design has no opinion on is left untouched so a
/// manually-chosen model is never clobbered. A missing `(model …)` block that
/// the design *should* have is treated as drift (one-time backfill). The board
/// stores `writeModelBlock`'s negated form — offset `= -config`, rotate
/// `= (-rotX, rotY, rotZ)` — so the comparison negates the config to match.
fn modelDrifted(d: *DiffContext, inst: export_kicad.FlatInstance, m: BoardFp, fp_name_short: []const u8) bool {
    const mcfg = d.spc.model_cfg.get(fp_name_short);
    const resolves_model = if (mcfg) |c|
        (c.model != null or fp_mod.findModelFile(d.spc.arena, d.spc.project_dir, fp_name_short, inst.component) != null)
    else
        fp_mod.findModelFile(d.spc.arena, d.spc.project_dir, fp_name_short, inst.component) != null;
    if (!resolves_model) return false;
    if (!m.has_model) return true; // should carry a model but doesn't → backfill

    const cfg_off = if (mcfg) |c| c.offset else [3]f64{ 0, 0, 0 };
    const cfg_rot = if (mcfg) |c| c.rotation else [3]f64{ 0, 0, 0 };
    const want_off = [3]f64{ -cfg_off[0], -cfg_off[1], -cfg_off[2] };
    const want_rot = [3]f64{ -cfg_rot[0], cfg_rot[1], cfg_rot[2] };
    for (0..3) |i| {
        if (@abs(m.model_offset[i] - want_off[i]) > model_drift_eps) return true;
        if (@abs(m.model_rotate[i] - want_rot[i]) > model_drift_eps) return true;
    }
    return false;
}

fn handleInstance(d: *DiffContext, inst: export_kicad.FlatInstance, w: anytype, first: *bool) !void {
    const fp_name_short = stripLibPrefix(inst.footprint);
    // Only passives carry a canopy_net field (it names the hub pin each pad
    // bridges to). Computed once here so both the matched set_field path and
    // the add bake-in path use the same value.
    const canopy_net = if (isPassiveRef(inst.ref_des))
        try buildCanopyNetValue(d.spc.arena, inst.ref_des, d.pad_net_map, d.pad_full_net, d.net_hub_pins)
    else
        null;
    const section = sectionForRef(inst.ref_des, d.ref_to_section);
    var counts: MatchCounts = .{};
    if (matchInstance(d, inst)) |m| {
        try handleMatched(d, inst, m, fp_name_short, canopy_net, section, w, first, &counts);
        // Count a matched footprint as "updated" only when a *material* op
        // landed — a value edit, footprint swap, or pad-net rewire (something
        // that actually changes the board). A match whose only ops were
        // metadata field writes (refdes rename, canopy_*/BOM-field stamps —
        // "nothing moves") is `relabeled` instead, so a refdes-heavy refactor
        // no longer inflates the update count. A no-diff sync touches neither.
        if (counts.material > 0) {
            d.summary.updated += 1;
        } else if (counts.meta > 0) {
            d.summary.relabeled += 1;
        }
        return;
    }
    // Defer the add — `emitStagedAdds` lays buffered adds out grouped by
    // section once the whole walk is done. fp_name / canopy_net / section
    // are resolved now; kmod is loaded at emit time.
    try d.pending_adds.append(d.spc.arena, .{
        .inst = inst,
        .fp_name = fp_name_short,
        .canopy_net = canopy_net,
        .section = section,
    });
}

/// Resolve which design section an instance belongs to. Sub-block parts
/// (hierarchical ref-des like "usb/U1") are attributed to their sub-block
/// name; top-level parts use the `(section …)` they were declared in;
/// anything else returns "" (no box, no canopy_section field).
fn sectionForRef(ref_des: []const u8, ref_to_section: *std.StringHashMapUnmanaged([]const u8)) []const u8 {
    if (std.mem.indexOfScalar(u8, ref_des, '/')) |i| return ref_des[0..i];
    return ref_to_section.get(ref_des) orelse "";
}

fn emitOp(w: anytype, first: *bool, op: []const u8, fields: anytype) !void {
    if (!first.*) try w.writeAll(",");
    first.* = false;
    try w.writeAll("{\"op\":\"");
    try w.writeAll(op);
    try w.writeAll("\"");
    inline for (fields) |kv| {
        try w.writeAll(",");
        try w.print("\"{s}\":", .{kv[0]});
        try json_writer.writeString(w, kv[1]);
    }
    try w.writeAll("}");
}

/// Bake a netlisp-model rotation (deg, page CW-positive) into KiCad's stored
/// `(at … angle)` for a footprint on `back` ? B.Cu : F.Cu. KiCad's angle is
/// CCW-positive, so the model angle is negated; a back part's netlisp local-X
/// mirror vs KiCad's stored local-Y mirror differ by a half-turn folded in here
/// (see `emitAddOp`'s call site for the full rationale). `kicadRotToNetlisp` is
/// the exact inverse — the round-trip is unit-tested for both sides.
fn netlispRotToKicad(rot_deg: f64, back: bool) f64 {
    const back_half_turn: f64 = if (back) 180.0 else 0.0;
    return @mod(360.0 - rot_deg + back_half_turn, 360.0);
}

/// Read a placed footprint's netlisp-model rotation back off the board, undoing
/// `netlispRotToKicad`. The bake is its own inverse in this algebra (`net = mod(
/// 360 − kicad + (back?180:0), 360)`), so a footprint's stored `(at)` angle and
/// its `B.`-prefixed layer recover the model rotation the seeder reasons in.
fn kicadRotToNetlisp(kicad_rot: f64, back: bool) f64 {
    const back_half_turn: f64 = if (back) 180.0 else 0.0;
    return @mod(360.0 - kicad_rot + back_half_turn, 360.0);
}

/// Where a first-insert footprint lands: staging position (board nm),
/// rotation (deg, page CW-positive — negated for KiCad inside emitAddOp),
/// and which board side it goes on.
const AddPose = struct { x_nm: i64, y_nm: i64, rot_deg: f64 = 0, back: bool = false };

fn emitAddOp(
    w: anytype,
    first: *bool,
    inst: export_kicad.FlatInstance,
    fp_name: []const u8,
    kmod: []const u8,
    pad_net_map: *std.StringHashMapUnmanaged([]const u8),
    pose: AddPose,
    canopy_net: ?[]const u8,
    section: []const u8,
) !void {
    if (!first.*) try w.writeAll(",");
    first.* = false;
    try w.writeAll("{\"op\":\"add\",\"uuid\":");
    try json_writer.writeString(w, inst.uuid);
    try w.writeAll(",\"ref\":");
    try json_writer.writeString(w, inst.ref_des);
    try w.writeAll(",\"value\":");
    try json_writer.writeString(w, inst.value);
    try w.writeAll(",\"footprint_name\":");
    try json_writer.writeString(w, fp_name);
    try w.writeAll(",\"kicad_mod\":");
    try json_writer.writeString(w, kmod);
    // Bake routing and section metadata into fresh footprints on the first sync.
    if (canopy_net) |cn| {
        if (cn.len > 0) {
            try w.writeAll(",\"canopy_net\":");
            try json_writer.writeString(w, cn);
        }
    }
    if (section.len > 0) {
        try w.writeAll(",\"canopy_section\":");
        try json_writer.writeString(w, section);
    }
    // Design properties (MPN, Manufacturer, Datasheet, … — every BOM column
    // except KiCad built-ins) baked into the add so they land on the FIRST
    // sync. The writer reads this array. Without it the file path created the fp with
    // only ref/value/canopy_*, and the rest didn't appear until a 2nd sync
    // emitted set_field ops against the now-existing part ("press sync twice").
    // Filtering mirrors the update path (skipDesignProperty + canonicalFieldName)
    // so the first sync bakes exactly what the second would set — no residual diff.
    try w.writeAll(",\"properties\":[");
    var prop_first = true;
    for (inst.properties) |p| {
        if (skipDesignProperty(p.key)) continue;
        if (p.value.len == 0) continue;
        if (!prop_first) try w.writeAll(",");
        prop_first = false;
        try w.writeAll("{\"key\":");
        try json_writer.writeString(w, canonicalFieldName(p.key));
        try w.writeAll(",\"value\":");
        try json_writer.writeString(w, p.value);
        try w.writeAll("}");
    }
    try w.writeAll("]");
    // Staging position (board nm). Both paths move the new fp here; (0,0)
    // means "no staging hint" (the part stays at the origin).
    try w.print(",\"x\":{d},\"y\":{d}", .{ pose.x_nm, pose.y_nm });
    // Orientation. The placement engine's angle is CW-positive (the page's
    // `wpt()` rotates with SVG `rotate()` in a Y-down world), but KiCad's
    // `(at x y angle)` is CCW-positive — so emit the negated angle. 0/180 are
    // self-inverse (no change); only 90↔270 swap, which is exactly why vertical
    // passives were landing 180° flipped while horizontal ones looked fine.
    // Negating here also keeps each pad where the EDA computed it, so the GND
    // vias (placed at EDA pad centres) still land on the right KiCad pads.
    // The staging grid passes 0 → stays the writer's bare `(at x y)` form.
    //
    // Bottom-side parts additionally get +180°: netlisp mirrors footprint-local
    // X (before rotation) for a bottom part, while KiCad's stored back-side
    // convention mirrors local Y (see writer.adaptKmodChild) — the two mirrors
    // differ by exactly a half-turn, folded into the stored angle here.
    const kicad_rot = netlispRotToKicad(pose.rot_deg, pose.back);
    if (kicad_rot != 0) try w.print(",\"rot\":{d}", .{kicad_rot});
    // Board side: the writer lands the new footprint on B.Cu with its geometry
    // adapted to KiCad's stored back-side form. Omitted for front (legacy shape).
    if (pose.back) try w.writeAll(",\"side\":\"bottom\"");
    try w.writeAll(",\"pad_nets\":");
    try writePadNetsArray(w, inst.ref_des, pad_net_map);
    try w.writeAll("}");
}

fn lessThanStr(_: void, a: []const u8, b: []const u8) bool {
    return std.mem.lessThan(u8, a, b);
}

/// Number of part columns for a roughly-square box holding `n` parts.
fn boxCols(n: usize) usize {
    if (n <= 1) return 1;
    const c: usize = numeric.toCount(@ceil(@sqrt(@as(f64, @floatFromInt(n)))));
    return if (c < 1) 1 else c;
}

/// Build a BoardGraphicShape rectangle (unfilled outline) on Dwgs.User as
/// an Any-wrapped proto-canonical object string. Mirrors `writeBoardShapeOpen`
/// + geometry but standalone rather than an inline footprint child.
fn boardRectItem(arena: std.mem.Allocator, x1: f64, y1: f64, x2: f64, y2: f64) ![]const u8 {
    var buf: std.Io.Writer.Allocating = .init(arena);
    const w = &buf.writer;
    try w.writeAll(proto_any_open ++ proto_type_url_boardshape ++ "\",\"layer\":\"" ++ proto_layer_dwgs_user ++ "\",");
    try w.writeAll("\"shape\":{\"attributes\":{\"stroke\":{\"width\":");
    try w.print("{{\"valueNm\":{d}}},\"style\":\"SLS_DEFAULT\"}},", .{mmToNm(stage_box_stroke_mm)});
    try w.writeAll("\"fill\":{\"fillType\":\"GFT_UNFILLED\"}},");
    try writeRectGeom(w, x1, y1, x2, y2);
    try w.writeAll("}}");
    return buf.written();
}

/// Build a BoardText label on Dwgs.User as an Any-wrapped proto string.
fn boardLabelItem(arena: std.mem.Allocator, x: f64, y: f64, text: []const u8) ![]const u8 {
    var buf: std.Io.Writer.Allocating = .init(arena);
    const w = &buf.writer;
    try w.writeAll(proto_any_open ++ proto_type_url_boardtext ++ "\",\"layer\":\"" ++ proto_layer_dwgs_user ++ "\",\"text\":{\"position\":");
    try writeProtoVec2(w, x, y);
    try w.writeAll(",\"attributes\":{\"size\":");
    try writeProtoVec2(w, stage_label_size_mm, stage_label_size_mm);
    try w.writeAll("},\"text\":");
    try json_writer.writeString(w, text);
    try w.writeAll("}}");
    return buf.written();
}

/// Group buffered section-add indices by section name (sorted for a stable
/// layout) so `emitStagedAdds` can lay each section out as its own box.
fn groupAddsBySection(
    arena: std.mem.Allocator,
    adds: []const PendingAdd,
    buckets: *std.StringHashMapUnmanaged(std.ArrayList(usize)),
    order: *std.ArrayList([]const u8),
) !void {
    for (adds, 0..) |pa, i| {
        const key = if (pa.section.len > 0) pa.section else "(unsectioned)";
        const e = try buckets.getOrPut(arena, key);
        if (!e.found_existing) {
            e.value_ptr.* = .empty;
            try order.append(arena, key);
        }
        try e.value_ptr.append(arena, i);
    }
    std.mem.sort([]const u8, order.items, {}, lessThanStr);
}

/// Emit every buffered `add`, choosing each part's placement in three tiers:
///   1. **Per-sub-block module layout** — a not-yet-placed sub-block is seeded
///      from *its own* module default layout, as one pre-laid-out unit in the
///      staging area (drag into place in KiCad). See `seedSubBlocks`.
///   2. **Whole-design premade layout** (fresh boards only — see
///      `DiffContext.board_fresh`) — a remaining part the design's own
///      layout names lands at that exact (x, y, rot).
///   3. **Section-staging grid** — anything left clusters in a staging box.
/// Existing/matched footprints are never moved by any tier.
///
/// Tier 1 is **bypassed** when the design's own layout already places every
/// buffered add on a fresh board (`layoutNamesEveryAdd`). Module seeding exists
/// for parts the design layout does NOT place; when it places all of them, that
/// layout is the more specific authority — it positions the modules relative to
/// each other and carries each part's rotation and side, none of which survives
/// a trip through the staging band. Running tier 1 first there sent every
/// sub-block child off to ~300 mm and reproduced only the unmodularised
/// remainder in place. `?no_seed_blocks=1` (`SeedOptions.sub_blocks`) forces the
/// same bypass when the layout covers most, but not all, of the board.
///
/// When the request carries an explicit sub-circuit selection (the Push modal's
/// checkboxes — `seed_groups`/`seed_all`), that path takes over instead: the
/// selected groups are seeded from the saved whole-design layout (anchored on
/// their main IC if it's already on the board, else an off-board box, see
/// `seedSelectedGroups`) and everything else falls straight to the staging
/// grid. The default (no selection) flow above is left byte-for-byte unchanged.
fn emitStagedAdds(d: *DiffContext, w: anytype, first: *bool) !void {
    const arena = d.spc.arena;
    const adds = d.pending_adds.items;
    if (adds.len == 0) return;

    var leftover: std.ArrayList(PendingAdd) = .empty;

    // Explicit selection: seed the chosen sub-circuits from the saved layout,
    // send the rest (unselected groups + parts the layout doesn't name) to the
    // plain staging grid. Bypasses the module-layout / board_fresh tiers — the
    // user has asked for the whole-design layout regardless of board state.
    // `planSelectedGroups` decides placements; the writing stays here (it owns
    // the ops writer) so the helpers need no `anytype` writer param.
    if (d.seed.groups != null or d.seed.all) {
        const plan = try planSelectedGroups(d, adds, &leftover);
        for (plan.placed) |p| {
            const pa = p.pa;
            const kmod = loadKicadMod(d.spc, pa.fp_name, pa.inst.component) orelse continue;
            const ap = AddPose{ .x_nm = mmToNm(p.x_mm), .y_nm = mmToNm(p.y_mm), .rot_deg = p.rot, .back = p.back };
            try emitAddOp(w, first, pa.inst, pa.fp_name, kmod, d.pad_net_map, ap, pa.canopy_net, pa.section);
            d.summary.added += 1;
        }
        // One off-board box per seeded sub-circuit: a labelled rectangle around
        // it + a KiCad `(group …)` op so each module's parts drag as their own
        // unit, referenced by their canopy_uuids (= the footprints' KiCad uuids
        // for fresh adds). The shared offset already preserves inter-block
        // geometry; the per-box framing just makes each sub-circuit draggable.
        for (plan.boxes) |b| {
            const items = [_][]const u8{
                try boardRectItem(arena, b.x0, b.y0, b.x1, b.y1),
                try boardLabelItem(arena, (b.x0 + b.x1) * stage_half, b.y0 + stage_label_h_mm * stage_half, b.label),
            };
            for (items) |item_json| {
                if (!first.*) try w.writeAll(",");
                first.* = false;
                try w.writeAll(board_item_op_open);
                try w.writeAll(item_json);
                try w.writeAll("}");
            }
            if (b.members.len > 0) {
                if (!first.*) try w.writeAll(",");
                first.* = false;
                try w.writeAll("{\"op\":\"group\",\"name\":");
                try json_writer.writeString(w, b.label);
                try w.writeAll(",\"members\":[");
                for (b.members, 0..) |m, i| {
                    if (i > 0) try w.writeAll(",");
                    try json_writer.writeString(w, m);
                }
                try w.writeAll("]}");
            }
        }
        // Carry each seeded sub-circuit's module routing onto the board, offset to
        // sit under its footprints (the whole-design via path is skipped when any
        // block seeds — see the emitLayoutVias call site).
        try emitSeedCopper(d, w, first, plan.copper);
        return emitStagingGrid(d, w, first, leftover.items);
    }

    // Tier 1: seed sub-blocks that aren't on the board from their module
    // layouts — unless the design's own layout is already placing all of them.
    if (seedsSubBlocks(d)) {
        try seedSubBlocks(d, w, first, adds, &leftover);
    } else {
        for (adds) |pa| try leftover.append(arena, pa);
    }
    const rest = leftover.items;
    if (rest.len == 0) return;

    // Tier 2: the whole-design premade layout names the part → exact pose.
    // Fresh boards only — on a populated board the layout's coordinates land
    // in the middle of existing placement/routing, so everything left over
    // goes to the off-board staging grid instead.
    const layout_if_fresh = if (d.board_fresh or d.authoritative_layout != null) d.premade_layout else null;
    const layout = layout_if_fresh orelse return emitStagingGrid(d, w, first, rest);
    var grid_rest: std.ArrayList(PendingAdd) = .empty;
    for (rest) |pa| {
        const pose = layout.get(pa.inst.ref_des) orelse {
            try grid_rest.append(arena, pa);
            continue;
        };
        const kmod = loadKicadMod(d.spc, pa.fp_name, pa.inst.component) orelse continue;
        const ap = AddPose{ .x_nm = mmToNm(pose.x), .y_nm = mmToNm(pose.y), .rot_deg = pose.rot, .back = pose.side == .bottom };
        try emitAddOp(w, first, pa.inst, pa.fp_name, kmod, d.pad_net_map, ap, pa.canopy_net, pa.section);
        d.summary.added += 1;
    }
    // Tier 3: grid staging.
    return emitStagingGrid(d, w, first, grid_rest.items);
}

// ── Explicit per-sub-circuit layout seeding (Push modal checkboxes) ──────────

/// The chosen anchor of a sub-circuit group plus whether it is already on the
/// target board. The anchor is the group's "main part" (highest `anchorRank`,
/// ties → lowest ref-des); when it's on the board its live position lets
/// `seedSelectedGroups` re-centre the group's saved layout there (the IC stays
/// put, the rest of the sub-circuit flows in around it). `ref` is the flattened
/// ref-des used to look the anchor's saved pose up in the whole-design layout;
/// `origin_key` is the anchor instance's stable module-local key, used to look
/// it up in a module's origin-key-keyed layout (see `SubCircuitSrc.is_module`)
/// even when the anchor is already placed and thus absent from the pending adds.
const GroupAnchor = struct {
    ref: []const u8,
    origin_key: []const u8 = "",
    on_board: bool = false,
    board_x: f64 = 0,
    board_y: f64 = 0,
    /// The anchor footprint's netlisp-model rotation + side as placed on the
    /// board (decoded from its `(at)` angle + layer via `kicadRotToNetlisp`).
    /// `placeOneSelected` composes these into the group transform so a seeded
    /// sub-circuit follows a rotated / bottom-side anchor, not just its position.
    board_rot: f64 = 0,
    board_back: bool = false,
};

/// Rank a flattened ref-des as a placement anchor by its prefix letter: an IC
/// (`U`) outranks a connector / large hub (`J`/`P`/`X`/`Q`), which outranks any
/// passive or other part. Classifies the leaf after the last `/` so a sub-block
/// part (`mcu/U12`) is judged on `U12`, not the sub-block name.
fn anchorRank(ref_des: []const u8) u8 {
    const leaf = if (std.mem.lastIndexOfScalar(u8, ref_des, '/')) |i| ref_des[i + 1 ..] else ref_des;
    if (leaf.len == 0) return 0;
    return switch (leaf[0]) {
        'U' => 3,
        'J', 'P', 'X', 'Q' => 2,
        else => 1,
    };
}

/// Pick each sub-circuit group's anchor (see `GroupAnchor`); resolve whether it's
/// on the board by sharing `d`'s indexes so the match runs the diff loop's relink
/// tiers. Groups are `sectionForRef`'s keys; live pos from `board_positions`.
fn computeGroupAnchors(
    arena: std.mem.Allocator,
    instances: []const export_kicad.FlatInstance,
    d: *const DiffContext,
    board_positions: ?*const std.StringHashMapUnmanaged(FpPlacement),
) !std.StringHashMapUnmanaged(GroupAnchor) {
    var out = std.StringHashMapUnmanaged(GroupAnchor).empty;
    var rank_of = std.StringHashMapUnmanaged(u8).empty;
    for (instances) |inst| {
        const sec = sectionForRef(inst.ref_des, d.ref_to_section);
        if (sec.len == 0) continue;
        const rank = anchorRank(inst.ref_des);
        const better = blk: {
            const prev = rank_of.get(sec) orelse break :blk true;
            if (rank != prev) break :blk rank > prev;
            // Equal rank → keep the lexicographically smaller ref (deterministic).
            const cur = out.get(sec) orelse break :blk true;
            break :blk std.mem.lessThan(u8, inst.ref_des, cur.ref);
        };
        if (!better) continue;
        var ga = GroupAnchor{ .ref = inst.ref_des, .origin_key = inst.origin_key };
        // Diff loop's own relink tiers (matchInstance): netsig/uuid/ref/migration.
        const bfp: ?BoardFp = d.by_netsig.get(inst.uuid) orelse d.by_uuid.get(inst.uuid) orelse
            d.by_ref.get(inst.ref_des) orelse d.by_migration.get(inst.uuid);
        if (bfp) |m| {
            if (board_positions) |bp| {
                if (m.kicad_uuid.len > 0) {
                    if (bp.get(m.kicad_uuid)) |p| {
                        ga.on_board = true;
                        ga.board_x = p.x;
                        ga.board_y = p.y;
                        ga.board_back = std.mem.startsWith(u8, p.layer, "B.");
                        ga.board_rot = kicadRotToNetlisp(p.rot, ga.board_back);
                    }
                }
            }
        }
        try rank_of.put(arena, sec, rank);
        try out.put(arena, sec, ga);
    }
    return out;
}

/// Whether sub-circuit group `sec` was selected for layout seeding.
fn groupSelected(d: *DiffContext, sec: []const u8) bool {
    if (d.seed.all) return true;
    const set = d.seed.groups orelse return false;
    return set.contains(sec);
}

/// One fresh add placed at an absolute board coordinate (mm) by the seeding
/// planner. `emitStagedAdds` turns each into an `add` op (it owns the writer).
const PositionedAdd = struct { pa: PendingAdd, x_mm: f64, y_mm: f64, rot: f64, back: bool = false };
/// A group add with its already-resolved pre-offset board position (mm + rot)
/// and its sub-circuit name (the `sectionForRef` key — the sub-block slug, e.g.
/// `mcu`). The position is the part's source pose (module ★ layout for a
/// sub-block, else the parent cache) re-anchored so the sub-circuit's IC lands
/// at its parent-cache spot; `finishOffBoardBlock` then applies ONE shared
/// off-board offset over the whole block and bins these into one box + group
/// per sub-circuit.
const NamedAdd = struct { pa: PendingAdd, bx: f64, by: f64, rot: f64, sec: []const u8 };
/// One off-board labelled box (mm) bounding a single seeded sub-circuit whose IC
/// is NOT already on the board, plus that sub-circuit's canopy_uuids so the
/// writer binds them into their own draggable KiCad `(group …)`. `emitStagedAdds`
/// draws the rect/label + group op once per box.
const SeedBox = struct { x0: f64, y0: f64, x1: f64, y1: f64, label: []const u8, members: []const []const u8 };
/// One seeded sub-circuit's module copper to carry onto the board: the module ★
/// snapshot's routes (module-local mm + module-local net names), the module → parent
/// net-name bridge, the sub-block slug (for the private-net `<slug>/NET` fallback),
/// and the rigid `xform` applied to that sub-circuit's parts — so `emitSeedCopper`
/// transforms the copper by the SAME transform the footprints got (mirroring +
/// F.Cu↔B.Cu layer swap on a flip, a pure translation on the common same-side case).
const SeedCopper = struct {
    routes: pcb_layout.SavedRoutes,
    net_map: std.StringHashMapUnmanaged([]const u8),
    slug: []const u8,
    xform: Pose2D,
};
/// The output collectors `placeOneSelected` appends into, bundled so its
/// signature stays small: `leftover` (parts the source doesn't name), `placed`
/// (on-board positioned adds), `block` (off-board parts awaiting the shared
/// offset), and the two copper buckets — `copper` (on-board, final offset) and
/// `block_copper` (off-board, the shared block offset added in `planSelectedGroups`).
const SeedAccum = struct {
    leftover: *std.ArrayList(PendingAdd),
    placed: *std.ArrayList(PositionedAdd),
    block: *std.ArrayList(NamedAdd),
    copper: *std.ArrayList(SeedCopper),
    block_copper: *std.ArrayList(SeedCopper),
};
/// The seeding planner's output: positioned adds, one off-board box per seeded
/// sub-circuit (empty when every selected group anchored on the board), and the
/// per-sub-circuit module copper to lay down (empty when no seeded sub-block had
/// routed copper).
const SeedPlan = struct { placed: []const PositionedAdd, boxes: []const SeedBox, copper: []const SeedCopper };
/// `finishOffBoardBlock`'s result: the per-sub-circuit labelled boxes plus the ONE
/// shared (dx, dy) mm offset applied to the whole off-board block — so its copper
/// can be shifted by the identical amount its parts were.
const OffBoardResult = struct { boxes: []const SeedBox, dx: f64, dy: f64 };

/// Fallback box label for off-board seeded parts that carry no sub-circuit name
/// (top-level parts not inside a sub-block).
const seed_box_label = "Seeded layout — drag onto board";

/// The pose source for one selected sub-circuit. A sub-block with its OWN saved
/// module layout (`lib/modules/<m>.layouts.json`, ★-default) reads THAT so the
/// module reproduces exactly what the user starred for it: `is_module = true`,
/// the map is keyed by stable `origin_key` (matched per part on
/// `FlatInstance.origin_key`, which survives `(hierarchical-ids)` renumbering).
/// Everything else (sections, sub-blocks with no module layout) falls back to
/// the parent design cache: `is_module = false`, keyed by full flattened ref.
/// A module source also carries the snapshot's routed copper (`routes`) and the
/// module-pin → net bridge (`pin_nets`), so `emitSeedCopper` can lay the module's
/// hand routing onto the board; both are empty on the parent-cache path.
const SubCircuitSrc = struct {
    map: std.StringHashMapUnmanaged(pcb_layout.SyncPose),
    is_module: bool,
    routes: ?pcb_layout.SavedRoutes = null,
    pin_nets: []const pcb_layout.SubPinNet = &.{},
};

/// Resolve the pose source for sub-circuit `sec` (see `SubCircuitSrc`). Null when
/// neither a module layout nor the parent cache can supply poses.
fn subCircuitSource(d: *DiffContext, sec: []const u8) !?SubCircuitSrc {
    if (subBlockNamed(d.sub_blocks, sec)) |sb| {
        // Module layout keyed by origin_key (survives the parent's ref-des
        // renumbering), matched per part on FlatInstance.origin_key.
        if (pcb_layout.subBlockPoseByOriginKey(d.spc.arena, d.spc.project_dir, sb)) |s|
            return .{ .map = s.map, .is_module = true, .routes = s.routes, .pin_nets = s.pin_nets };
    }
    if (d.premade_layout) |cache| return .{ .map = cache, .is_module = false };
    return null;
}

/// Plan placement for an explicit sub-circuit selection (the Push modal). Each
/// selected sub-circuit's freshly-added parts take their *source* poses — the
/// sub-block's own starred module layout when it has one, else the parent design
/// cache (`subCircuitSource`) — re-anchored so the sub-circuit's main IC lands on
/// its target:
///   • IC already on the board ⇒ parts flow in AROUND that IC's live position
///     (the IC stays put), placed directly on the board;
///   • otherwise ⇒ the IC lands at its parent-cache spot and the parts join one
///     shared OFF-BOARD block.
/// So the off-board block keeps the whole board's INTER-block geometry (every
/// module sits where the design solve put it) while each module keeps its OWN
/// starred INTERNAL arrangement — and within that shared frame each sub-circuit
/// gets its own labelled box + draggable KiCad group. Parts no source names, and
/// non-selected groups, go to `leftover` for the caller's staging grid. Only
/// fresh adds get positions (existing footprints never move); no GND vias are
/// planned. Result lives on `arena`.
fn planSelectedGroups(
    d: *DiffContext,
    adds: []const PendingAdd,
    leftover: *std.ArrayList(PendingAdd),
) !SeedPlan {
    const arena = d.spc.arena;
    var placed: std.ArrayList(PositionedAdd) = .empty;
    var buckets = std.StringHashMapUnmanaged(std.ArrayList(usize)).empty;
    var order: std.ArrayList([]const u8) = .empty;
    try groupAddsBySection(arena, adds, &buckets, &order);

    // Off-board parts accumulate here (pre-offset board coords); the whole block
    // then shifts clear of the board with ONE shared offset.
    var block: std.ArrayList(NamedAdd) = .empty;
    var copper: std.ArrayList(SeedCopper) = .empty;
    var block_copper: std.ArrayList(SeedCopper) = .empty;
    var acc = SeedAccum{
        .leftover = leftover,
        .placed = &placed,
        .block = &block,
        .copper = &copper,
        .block_copper = &block_copper,
    };
    for (order.items) |sec| {
        const idxs = (buckets.get(sec) orelse continue).items;
        if (!groupSelected(d, sec)) {
            for (idxs) |idx| try leftover.append(arena, adds[idx]);
            continue;
        }
        const src = (try subCircuitSource(d, sec)) orelse {
            for (idxs) |idx| try leftover.append(arena, adds[idx]);
            continue;
        };
        try placeOneSelected(d, sec, idxs, adds, src, d.group_anchors.get(sec), &acc);
    }
    const ob = try finishOffBoardBlock(arena, block.items, &placed);
    d.summary.blocks += @intCast(ob.boxes.len);
    // The off-board block shifted by ONE shared offset; fold it into each of its
    // sub-circuits' copper (their per-group anchor offset was recorded already).
    for (block_copper.items) |c| {
        try copper.append(arena, .{
            .routes = c.routes,
            .net_map = c.net_map,
            .slug = c.slug,
            .xform = c.xform.translated(ob.dx, ob.dy),
        });
    }
    return .{ .placed = placed.items, .boxes = ob.boxes, .copper = copper.items };
}

/// A rigid 2-D placement transform in the netlisp pose model — the algebra a
/// seeded sub-circuit uses to follow its anchor IC onto a rotated / bottom-side
/// board pose. Maps a footprint-local point v to world as
/// `apply(v) = rotate(mirrorX(v)) + (tx,ty)`, where `mirrorX` negates x iff
/// `mirror` and `rotate` use the arbitrary-angle matrix of `optimizer.rotateLocal`
/// applied in the netlisp y-down frame. A part's `SyncPose` (x,y,rot,side) is
/// exactly such a transform (mirror ⟺ side==bottom) — the mirror-before-rotate
/// order matches `optimizer.worldPt`, the authoritative pose→pad-world math, so
/// composing these preserves every pad's relative position under a flip.
const Pose2D = struct {
    tx: f64 = 0,
    ty: f64 = 0,
    rot: f64 = 0,
    mirror: bool = false,

    /// `optimizer.rotateLocal`'s CCW matrix in the netlisp y-down frame.
    fn rotate(deg: f64, x: f64, y: f64) [2]f64 {
        return pose_math.rotate(x, y, deg);
    }

    /// Linear part only (rotate∘mirrorX, no translation).
    fn applyLin(self: Pose2D, x: f64, y: f64) [2]f64 {
        return rotate(self.rot, if (self.mirror) -x else x, y);
    }

    /// World point of footprint-local (x,y).
    fn apply(self: Pose2D, x: f64, y: f64) [2]f64 {
        const l = self.applyLin(x, y);
        return .{ l[0] + self.tx, l[1] + self.ty };
    }

    /// `self ∘ other` — apply `other` first, then `self`. Mirror XORs; rotation
    /// adds, negated by `self`'s mirror (since Mir·R(θ)=R(−θ)·Mir); translation
    /// is `self`'s linear part on `other`'s translation plus `self`'s own.
    fn compose(self: Pose2D, other: Pose2D) Pose2D {
        const t = self.applyLin(other.tx, other.ty);
        return .{
            .tx = t[0] + self.tx,
            .ty = t[1] + self.ty,
            .rot = @mod(self.rot + (if (self.mirror) -other.rot else other.rot), 360.0),
            .mirror = self.mirror != other.mirror,
        };
    }

    /// The inverse transform: `inverse() ∘ self == identity`.
    fn inverse(self: Pose2D) Pose2D {
        var out = Pose2D{ .rot = @mod(if (self.mirror) self.rot else -self.rot, 360.0), .mirror = self.mirror };
        const t = out.applyLin(self.tx, self.ty);
        out.tx = -t[0];
        out.ty = -t[1];
        return out;
    }

    /// Post-compose a pure translation (shift the transform's output by dx,dy) —
    /// how the off-board block's one shared offset folds into its copper transform.
    fn translated(self: Pose2D, dx: f64, dy: f64) Pose2D {
        return .{ .tx = self.tx + dx, .ty = self.ty + dy, .rot = self.rot, .mirror = self.mirror };
    }
};

/// A module ★-layout pose as a `Pose2D` (mirror ⟺ bottom side).
fn poseFromSync(sp: pcb_layout.SyncPose) Pose2D {
    return .{ .tx = sp.x, .ty = sp.y, .rot = sp.rot, .mirror = sp.side == .bottom };
}

/// The rigid transform that carries a seeded sub-circuit from its module ★
/// layout onto the board so its anchor IC lands on the anchor's LIVE board pose
/// — position, rotation, AND side: `board_anchor ∘ inverse(module_anchor)`.
/// Applying it to every part's module pose reproduces the module's internal
/// geometry exactly while flipping/rotating the whole group to match a
/// bottom-side or rotated anchor. Reduces to a pure translation (rot 0, no
/// mirror) when the anchor keeps the module's side and rotation — the common
/// same-side case, byte-identical to the old `target − src_anchor` offset.
fn groupTransform(module_anchor: pcb_layout.SyncPose, a: GroupAnchor) Pose2D {
    const board = Pose2D{ .tx = a.board_x, .ty = a.board_y, .rot = a.board_rot, .mirror = a.board_back };
    return board.compose(poseFromSync(module_anchor).inverse());
}

/// Place one selected sub-circuit's parts from its `src` poses, re-anchored so
/// the sub-circuit's IC lands on its target. When the IC is already on the board
/// the whole group rides a rigid `groupTransform` (position + rotation + side)
/// onto the board, so a bottom-side or rotated anchor takes its passives (and
/// copper) with it — the same-side, zero-rotation case reduces to the old pure
/// translation. Otherwise the IC lands at its parent-cache spot and the parts
/// join the shared OFF-BOARD block (top-side, translate-only, unchanged). Parts
/// the source doesn't name go to `leftover`.
fn placeOneSelected(
    d: *DiffContext,
    sec: []const u8,
    idxs: []const usize,
    adds: []const PendingAdd,
    src: SubCircuitSrc,
    anchor: ?GroupAnchor,
    acc: *SeedAccum,
) !void {
    const arena = d.spc.arena;
    var offx: f64 = 0;
    var offy: f64 = 0;
    var xform: Pose2D = .{}; // module-world → board-world (the on-board rigid transform)
    var on_board = false;
    if (anchor) |a| {
        // A module source is keyed by origin_key, so key the anchor by its own
        // `origin_key` (resolved from the flattened roster in
        // `computeGroupAnchors`). Its flattened ref-des won't key the map, and
        // this works even when the anchor IC is already placed — and thus absent
        // from `adds` — which is exactly when its passives must centre on it.
        const akey = if (src.is_module) a.origin_key else a.ref;
        if (src.map.get(akey)) |as_| {
            if (a.on_board) {
                on_board = true;
                xform = groupTransform(as_, a);
            } else if (d.premade_layout) |cache| if (cache.get(a.ref)) |cp| {
                offx = cp.x - as_.x;
                offy = cp.y - as_.y;
            };
        }
    }
    for (idxs) |idx| {
        const pa = adds[idx];
        const key = if (src.is_module) pa.inst.origin_key else pa.inst.ref_des;
        const sp = src.map.get(key) orelse {
            try acc.leftover.append(arena, pa);
            continue;
        };
        if (on_board) {
            const np = xform.compose(poseFromSync(sp));
            try acc.placed.append(arena, .{ .pa = pa, .x_mm = np.tx, .y_mm = np.ty, .rot = np.rot, .back = np.mirror });
        } else {
            try acc.block.append(arena, .{ .pa = pa, .bx = sp.x + offx, .by = sp.y + offy, .rot = sp.rot, .sec = sec });
        }
    }
    if (on_board) d.summary.blocks += 1;
    // Carry the module's routed copper along under the SAME transform its parts
    // got — the module-local coordinates share the pose frame. On-board copper
    // rides the rigid transform (mirroring endpoints + swapping F.Cu↔B.Cu when
    // flipped); off-board copper is a pure translation that still owes the shared
    // block offset, folded in by `planSelectedGroups`.
    if (src.is_module) if (src.routes) |sr| {
        const net_map = try subCircuitNetMap(d, src.pin_nets, idxs, adds);
        const cop_xform = if (on_board) xform else Pose2D{ .tx = offx, .ty = offy };
        const job = SeedCopper{ .routes = sr, .net_map = net_map, .slug = sec, .xform = cop_xform };
        try (if (on_board) acc.copper else acc.block_copper).append(arena, job);
    };
}

/// Map each of a seeded sub-circuit's module-local net names to the parent net
/// its pads carry on the board, so `emitSeedCopper` lays the copper on the same
/// net as the pads it connects. For each module pin sample `(net, origin_key,
/// pad)` the parent ref is `origin_key → ref` (the sub-circuit's freshly-added
/// parts — every net the seeded copper touches has at least one fresh pad), and
/// the parent net is that pad's display net from `d.pad_net_map` ("ref|pin") — the
/// exact spelling the netlist sync writes on the pad, so copper and pad agree even
/// when a bare name collided and kept its `<slug>/…` prefix. Unresolved nets fall
/// back to the `<slug>/NET` flatten spelling in `bridgedCopperNet`.
fn subCircuitNetMap(
    d: *DiffContext,
    pin_nets: []const pcb_layout.SubPinNet,
    idxs: []const usize,
    adds: []const PendingAdd,
) !std.StringHashMapUnmanaged([]const u8) {
    const arena = d.spc.arena;
    var ok_ref = std.StringHashMapUnmanaged([]const u8).empty;
    for (idxs) |i| {
        const inst = adds[i].inst;
        if (inst.origin_key.len == 0) continue;
        try ok_ref.put(arena, inst.origin_key, inst.ref_des);
    }
    var net_map = std.StringHashMapUnmanaged([]const u8).empty;
    for (pin_nets) |ps| {
        if (net_map.contains(ps.net)) continue;
        const dref = ok_ref.get(ps.origin_key) orelse continue;
        const key = try std.fmt.allocPrint(arena, "{s}|{s}", .{ dref, ps.pad });
        const dn = d.pad_net_map.get(key) orelse continue;
        try net_map.put(arena, ps.net, dn);
    }
    return net_map;
}

/// The parent-board net spelling for a module-local copper net: the bridged
/// parent display net when a module pin resolved (`net_map`), else the
/// `<slug>/NET` flatten spelling a module-private net takes in the parent netlist
/// (mirrors `pcb_layout_page.mappedNet`). Empty string ⇒ skip (unnamed copper).
fn bridgedCopperNet(
    arena: std.mem.Allocator,
    net_map: std.StringHashMapUnmanaged([]const u8),
    slug: []const u8,
    net: []const u8,
) []const u8 {
    if (net.len == 0) return "";
    if (net_map.get(net)) |m| return m;
    return std.fmt.allocPrint(arena, "{s}/{s}", .{ slug, net }) catch "";
}

/// KiCad copper-layer name for a router / `SavedTrack` layer index. The router
/// numbers signal layers 0 = top (F.Cu), 1 = bottom (B.Cu); the spellings come
/// from `board_layers`, so this path cannot drift from the Gerber/blob naming.
/// Seeded vias are through-hole, so they need no map.
///
/// CAVEAT — no `BoardRules` reaches here (the diff context carries the netlist,
/// not the stackup), so an inner index is read as its OWN stack position. That
/// is exact for every board whose inner layers are all routable, and understates
/// by one plane for a stackup that declares a plane-claimed inner. Handing this
/// path the board's layer table is a follow-up; it is deliberately unchanged
/// here so no board's exported copper moves.
fn kicadCopperLayer(arena: std.mem.Allocator, l: u8) ![]const u8 {
    if (l == 0) return board_layers.f_cu;
    if (l == 1) return board_layers.b_cu;
    var buf: [board_layers.name_buf_len]u8 = undefined;
    return try arena.dupe(u8, board_layers.innerName(board_layers.StackIndex.of(l), &buf));
}

/// The router layer index a seeded track/via takes after its group's transform:
/// a flipped group (`mirror`) swaps its OUTER signal layers (F.Cu↔B.Cu, i.e.
/// 0↔1). Inner-layer indices (l≥2) are left as-is — module ★ copper is
/// essentially always outer (l∈{0,1}), and reversing an inner stack needs the
/// board's layer count, which isn't cheaply known here. `kicadCopperLayer` then
/// maps the (possibly swapped) index to its KiCad name.
fn copperLayerSided(l: u8, mirror: bool) u8 {
    if (!mirror) return l;
    return switch (l) {
        0 => 1,
        1 => 0,
        else => l,
    };
}

fn seedNetRule(d: *const DiffContext, display_name: []const u8) optimizer.NetRule {
    for (d.nets, 0..) |net, i| {
        if (i >= d.net_rules.len) break;
        if (std.ascii.eqlIgnoreCase(net.name, display_name)) return d.net_rules[i];
    }
    // `populatePadNetMaps` strips a hierarchy prefix only when the resulting
    // display name is globally unique, so this fallback cannot select an
    // ambiguous sibling net.
    for (d.nets, 0..) |net, i| {
        if (i >= d.net_rules.len) break;
        if (std.ascii.eqlIgnoreCase(bareNetName(net.name), display_name)) return d.net_rules[i];
    }
    return .{};
}

/// Emit `add_track` / `add_via` ops for each seeded sub-circuit's module copper
/// (`jobs`), applying the job's rigid `xform` to every endpoint/centre — the same
/// transform its footprints got, so a flipped group's copper mirrors and swaps
/// F.Cu↔B.Cu — and bridging module net names to parent nets. Named-only
/// (unbridged, empty-name) copper is skipped. Counted in `d.summary`.
fn emitSeedCopper(d: *DiffContext, w: anytype, first: *bool, jobs: []const SeedCopper) !void {
    const arena = d.spc.arena;
    for (jobs) |job| {
        for (job.routes.tracks) |t| {
            const net = bridgedCopperNet(arena, job.net_map, job.slug, t.net);
            if (net.len == 0) continue;
            const rule = seedNetRule(d, net);
            const width = if (rule.width > 0) rule.width else t.w;
            const layer = try kicadCopperLayer(arena, copperLayerSided(t.l, job.xform.mirror));
            const p1 = job.xform.apply(t.x1, t.y1);
            const p2 = job.xform.apply(t.x2, t.y2);
            if (!first.*) try w.writeAll(",");
            first.* = false;
            const mid = if (t.xm) |xm| if (t.ym) |ym| job.xform.apply(xm, ym) else null else null;
            try w.writeAll(if (mid != null) add_arc_op_open else add_track_op_open);
            try json_writer.writeString(w, net);
            if (mid) |pm| {
                try w.print(",\"x1\":{d},\"y1\":{d},\"xm\":{d},\"ym\":{d},\"x2\":{d},\"y2\":{d},\"width\":{d},\"layer\":", .{
                    mmToNm(p1[0]), mmToNm(p1[1]), mmToNm(pm[0]), mmToNm(pm[1]),
                    mmToNm(p2[0]), mmToNm(p2[1]), mmToNm(width),
                });
            } else {
                try w.print(track_coords_fmt, .{
                    mmToNm(p1[0]), mmToNm(p1[1]),
                    mmToNm(p2[0]), mmToNm(p2[1]),
                    mmToNm(width),
                });
            }
            try json_writer.writeString(w, layer);
            try w.writeAll(",\"group\":");
            try json_writer.writeString(w, if (job.slug.len > 0) job.slug else seed_box_label);
            try w.writeAll("}");
            d.summary.tracks += 1;
        }
        for (job.routes.vias) |v| {
            const net = bridgedCopperNet(arena, job.net_map, job.slug, v.net);
            if (net.len == 0) continue;
            const rule = seedNetRule(d, net);
            const dia = if (rule.via_dia > 0) rule.via_dia else v.d;
            const drill = if (rule.via_drill > 0) rule.via_drill else v.drill;
            const c = job.xform.apply(v.x, v.y);
            if (!first.*) try w.writeAll(",");
            first.* = false;
            try w.writeAll(add_via_op_open);
            try json_writer.writeString(w, net);
            try w.print(",\"x\":{d},\"y\":{d},\"dia\":{d},\"drill\":{d},\"group\":", .{
                mmToNm(c[0]), mmToNm(c[1]), mmToNm(dia), mmToNm(drill),
            });
            try json_writer.writeString(w, if (job.slug.len > 0) job.slug else seed_box_label);
            try w.writeAll("}");
            d.summary.vias += 1;
        }
    }
}

/// Translate the whole off-board `block` by ONE shared offset (its collective
/// min-corner → the off-board staging origin), so it reproduces the saved
/// layout's geometry exactly, appending the positioned parts to `placed`. Then
/// emit one labelled `SeedBox` per sub-circuit (`NamedAdd.sec`): each box bounds
/// only that sub-circuit's translated parts and carries only its member uuids,
/// so every module drags as its own KiCad group while keeping its position
/// relative to the others. Boxes come out in first-seen sub-circuit order;
/// returns an empty slice when `block` is empty. Result lives on `arena`.
fn finishOffBoardBlock(
    arena: std.mem.Allocator,
    block: []const NamedAdd,
    placed: *std.ArrayList(PositionedAdd),
) !OffBoardResult {
    if (block.len == 0) return .{ .boxes = &.{}, .dx = 0, .dy = 0 };
    // ONE shared offset from the whole block's collective min-corner.
    var minx: f64 = std.math.floatMax(f64);
    var miny: f64 = std.math.floatMax(f64);
    for (block) |n| {
        minx = @min(minx, n.bx);
        miny = @min(miny, n.by);
    }
    const dx = block_stage_origin_x_mm - minx;
    const dy = block_stage_origin_y_mm - miny;
    for (block) |n| {
        try placed.append(arena, .{ .pa = n.pa, .x_mm = n.bx + dx, .y_mm = n.by + dy, .rot = n.rot });
    }
    // One box + group per sub-circuit, in first-seen order.
    var boxes: std.ArrayList(SeedBox) = .empty;
    var seen = std.StringHashMapUnmanaged(void).empty;
    for (block) |first| {
        if (seen.contains(first.sec)) continue;
        try seen.put(arena, first.sec, {});
        var bx0: f64 = std.math.floatMax(f64);
        var by0: f64 = std.math.floatMax(f64);
        var bx1: f64 = -std.math.floatMax(f64);
        var by1: f64 = -std.math.floatMax(f64);
        var members: std.ArrayList([]const u8) = .empty;
        for (block) |n| {
            if (!std.mem.eql(u8, n.sec, first.sec)) continue;
            const x = n.bx + dx;
            const y = n.by + dy;
            bx0 = @min(bx0, x);
            by0 = @min(by0, y);
            bx1 = @max(bx1, x);
            by1 = @max(by1, y);
            if (n.pa.inst.uuid.len > 0) try members.append(arena, n.pa.inst.uuid);
        }
        try boxes.append(arena, .{
            .x0 = bx0 - stage_box_pad_mm,
            .y0 = by0 - stage_box_pad_mm - stage_label_h_mm,
            .x1 = bx1 + stage_box_pad_mm,
            .y1 = by1 + stage_box_pad_mm,
            .label = if (first.sec.len > 0) first.sec else seed_box_label,
            .members = members.items,
        });
    }
    return .{ .boxes = boxes.items, .dx = dx, .dy = dy };
}

/// Build the `sub_circuits` JSON array advertised in the dry-run response: one
/// entry per group whose freshly-added parts a saved layout can seed — counted
/// through the SAME source the Confirm path will use (`subCircuitSource`): a
/// sub-block reads its OWN starred module layout (`lib/modules/<m>.layouts.json`,
/// keyed by `origin_key`), a section reads the whole-design cache (keyed by
/// ref-des). So a design whose sub-modules are starred lists them even when it
/// has no whole-design layout of its own — previously this required a
/// whole-design layout and silently dropped every module-seedable sub-block.
/// Each entry carries the group `name`, the seedable `parts` count, the chosen
/// `anchor` ref (or null), and whether that anchor is already `on_board`. A
/// group with no seedable source is skipped. Computed from the still-populated
/// `pending_adds` after `emitStagedAdds`. Result lives on `arena`.
fn buildSubCircuitsJson(arena: std.mem.Allocator, d: *DiffContext) ![]const u8 {
    var buf: std.Io.Writer.Allocating = .init(arena);
    const w = &buf.writer;
    try w.writeByte('[');
    const adds = d.pending_adds.items;
    var buckets = std.StringHashMapUnmanaged(std.ArrayList(usize)).empty;
    var order: std.ArrayList([]const u8) = .empty;
    try groupAddsBySection(arena, adds, &buckets, &order);
    var emitted_first = true;
    for (order.items) |sec| {
        const idxs = (buckets.get(sec) orelse continue).items;
        // Resolve this group's pose source exactly as the seeder will, then
        // count how many of its adds that source names. No source (no module
        // layout and no whole-design cache) => nothing to seed => no checkbox.
        const src = (try subCircuitSource(d, sec)) orelse continue;
        var named: usize = 0;
        for (idxs) |idx| {
            const key = if (src.is_module) adds[idx].inst.origin_key else adds[idx].inst.ref_des;
            if (src.map.get(key) != null) named += 1;
        }
        if (named == 0) continue;
        // Module copper this group would carry onto the board (0 when the ★
        // snapshot has no routes, or when the source is the parent cache).
        const n_tracks = if (src.routes) |sr| sr.tracks.len else 0;
        const n_vias = if (src.routes) |sr| sr.vias.len else 0;
        const anchor = d.group_anchors.get(sec);
        if (!emitted_first) try w.writeByte(',');
        emitted_first = false;
        try w.writeAll("{\"name\":");
        try json_writer.writeString(w, sec);
        try w.print(",\"parts\":{d},\"tracks\":{d},\"vias\":{d},\"anchor\":", .{ named, n_tracks, n_vias });
        if (anchor) |a| {
            try json_writer.writeString(w, a.ref);
            try w.print(",\"on_board\":{}", .{a.on_board});
            // When the on-board anchor is bottom-side / rotated, the seed flips
            // the whole group to match — surface it so the Push modal can show it.
            if (a.on_board and a.board_back) try w.writeAll(",\"side\":\"bottom\"");
            if (a.on_board and a.board_rot != 0) try w.print(",\"rot\":{d}", .{a.board_rot});
        } else {
            try w.writeAll("null,\"on_board\":false");
        }
        try w.writeByte('}');
    }
    try w.writeByte(']');
    return buf.written();
}

/// Staging band for whole-sub-block seeds: blocks are packed left-to-right at
/// `BLOCK_STAGE_ORIGIN`, each preserving its module's internal arrangement, so a
/// not-yet-placed sub-block lands as a draggable unit clear of the main board.
const block_stage_origin_x_mm: f64 = 300.0;
const block_stage_origin_y_mm: f64 = 230.0;
const block_stage_gap_mm: f64 = 12.0;

/// True when the whole-design premade layout names EVERY buffered add — the
/// condition under which tier 2 alone reproduces the saved board exactly, with
/// nothing falling through to the staging grid. The one shared definition of "a
/// faithful whole-design seed": it gates the tier-1 bypass (`seedsSubBlocks`),
/// the computed stitching vias (`emitLayoutVias`) and the saved copper
/// (`emitLayoutCopper`), so all three agree about which board they describe.
/// Note the copper gates need this AFTER emission, which is safe because
/// `emitStagedAdds` reads `pending_adds` and never clears it.
fn layoutNamesEveryAdd(d: *const DiffContext) bool {
    const layout = d.premade_layout orelse return false;
    for (d.pending_adds.items) |pa| {
        if (!layout.contains(pa.inst.ref_des)) return false;
    }
    return true;
}

/// Whether tier 1 (per-sub-block module seeding) runs for this sync: only when
/// the caller hasn't opted out (`?no_seed_blocks=1`) and the design's own layout
/// isn't already placing the whole fresh board itself. See `emitStagedAdds`.
fn seedsSubBlocks(d: *const DiffContext) bool {
    if (d.authoritative_layout != null) return false;
    if (!d.seed.sub_blocks) return false;
    return !(d.board_fresh and layoutNamesEveryAdd(d));
}

/// Whether this sync just reproduced the design's saved layout onto a fresh
/// board in full — the precondition for writing that layout's copper. Requires a
/// FRESH board (on a populated one the saved coordinates land in the middle of
/// real routing), parts actually added, and the layout naming every one of them,
/// so the copper is guaranteed to sit under footprints at their saved poses.
/// Called AFTER emission, when `summary.added` is final.
fn seedsWholeLayout(d: *const DiffContext) bool {
    if (!d.board_fresh) return false;
    if (d.summary.added == 0) return false;
    return layoutNamesEveryAdd(d);
}

/// Tier 1 of `emitStagedAdds`: group the buffered adds by their sub-block
/// (`pa.section` is the sub-block name for a sub-block part), and for each group
/// whose sub-block has a module default layout, place its parts as one unit in
/// the staging band using that layout. Parts not in a module-layout sub-block —
/// or a sub-block part the module layout doesn't name — are appended to
/// `leftover` for tiers 2–3. Only the *missing* parts are placed (already-placed
/// parts never reach `pending_adds`), so this fills a partly-placed block too.
fn seedSubBlocks(d: *DiffContext, w: anytype, f: *bool, add: []const PendingAdd, lo: *std.ArrayList(PendingAdd)) !void {
    const arena = d.spc.arena;
    if (d.sub_blocks.len == 0) {
        for (add) |pa| try lo.append(arena, pa);
        return;
    }
    // Group add indices by section, in a stable (sorted) block order.
    var buckets = std.StringHashMapUnmanaged(std.ArrayList(usize)).empty;
    var order: std.ArrayList([]const u8) = .empty;
    for (add, 0..) |pa, i| {
        const e = try buckets.getOrPut(arena, pa.section);
        if (!e.found_existing) {
            e.value_ptr.* = .empty;
            try order.append(arena, pa.section);
        }
        try e.value_ptr.append(arena, i);
    }
    std.mem.sort([]const u8, order.items, {}, lessThanStr);

    var cursor_x = block_stage_origin_x_mm;
    for (order.items) |sec| {
        const idxs = (buckets.get(sec) orelse continue).items;
        // Not a sub-block, or a sub-block with no module default layout → defer.
        const sb = subBlockNamed(d.sub_blocks, sec) orelse {
            for (idxs) |idx| try lo.append(arena, add[idx]);
            continue;
        };
        // Poses re-keyed onto this sub-block's own flattened refs (by origin_key)
        // so a module layout saved in a different design's ref-namespace still maps.
        const poses = pcb_layout.loadSubBlockPoses(arena, d.spc.project_dir, sb) orelse {
            for (idxs) |idx| try lo.append(arena, add[idx]);
            continue;
        };
        if (try seedOneSubBlock(d, w, f, sb, sec, add, idxs, poses, cursor_x, lo)) |advance|
            cursor_x += advance;
    }
}

/// Place one sub-block's missing parts at `cursor_x` in the staging band, using
/// `poses` (module-local). Returns the horizontal advance (block width + gap) to
/// pack the next block, or null when nothing was placed (no box drawn, cursor
/// unchanged). The module layout is keyed by the module's ref-des, which equals
/// the design's flattened sub-block ref minus the `<sec>/` prefix (both resolve
/// through the same instantiation), so a prefix-strip maps them.
fn seedOneSubBlock(
    d: *DiffContext,
    w: anytype,
    first: *bool,
    sb: env_mod.SubBlock,
    sec: []const u8,
    adds: []const PendingAdd,
    idxs: []const usize,
    poses: []const pcb_layout.RefPose,
    cursor_x: f64,
    leftover: *std.ArrayList(PendingAdd),
) !?f64 {
    const arena = d.spc.arena;
    var pmap = std.StringHashMapUnmanaged(pcb_layout.SyncPose).empty;
    var minx: f64 = std.math.floatMax(f64);
    var miny: f64 = std.math.floatMax(f64);
    var maxx: f64 = -std.math.floatMax(f64);
    var maxy: f64 = -std.math.floatMax(f64);
    for (poses) |p| {
        try pmap.put(arena, p.ref, .{ .x = p.x, .y = p.y, .rot = p.rot });
        minx = @min(minx, p.x);
        miny = @min(miny, p.y);
        maxx = @max(maxx, p.x);
        maxy = @max(maxy, p.y);
    }
    // Block-space → board-space translation: the block's min corner lands at
    // (cursor_x, BLOCK_STAGE_ORIGIN_Y), preserving the internal layout.
    const dx = cursor_x - minx;
    const dy = block_stage_origin_y_mm - miny;

    var seeded: usize = 0;
    for (idxs) |idx| {
        const pa = adds[idx];
        const local = stripSubPrefix(pa.inst.ref_des, sec);
        const pose = pmap.get(local) orelse {
            try leftover.append(arena, pa);
            continue;
        };
        const kmod = loadKicadMod(d.spc, pa.fp_name, pa.inst.component) orelse continue;
        try emitAddOp(
            w,
            first,
            pa.inst,
            pa.fp_name,
            kmod,
            d.pad_net_map,
            .{
                .x_nm = mmToNm(pose.x + dx),
                .y_nm = mmToNm(pose.y + dy),
                .rot_deg = pose.rot,
                .back = pose.side == .bottom,
            },
            pa.canopy_net,
            pa.section,
        );
        d.summary.added += 1;
        seeded += 1;
    }
    if (seeded == 0) return null;
    d.summary.blocks += 1;

    // Outline + label box around the block's footprint extent.
    const bx0 = cursor_x - stage_box_pad_mm;
    const by0 = block_stage_origin_y_mm - stage_box_pad_mm - stage_label_h_mm;
    const bx1 = cursor_x + (maxx - minx) + stage_box_pad_mm;
    const by1 = block_stage_origin_y_mm + (maxy - miny) + stage_box_pad_mm;
    const items = [_][]const u8{
        try boardRectItem(arena, bx0, by0, bx1, by1),
        try boardLabelItem(arena, (bx0 + bx1) * stage_half, by0 + stage_label_h_mm * stage_half, sec),
    };
    for (items) |item_json| {
        if (!first.*) try w.writeAll(",");
        first.* = false;
        try w.writeAll(board_item_op_open);
        try w.writeAll(item_json);
        try w.writeAll("}");
    }

    // GND vias only on a fresh board AND when the WHOLE block is fresh (every
    // module part was a fresh add). On a populated board the staged block gets
    // dragged into place, but vias don't travel with footprints — they'd stay
    // stranded in the staging band. A partly-placed block's other parts live
    // elsewhere on the board, so block-frame vias for them would strand too.
    if (d.seed.layout_vias and d.board_fresh and seeded == poses.len)
        try emitBlockVias(d, w, first, sb.block, poses, dx, dy);

    return (bx1 - bx0) + block_stage_gap_mm;
}

/// Emit the GND vias for a fully-fresh seeded sub-block: route its module layout
/// in the block's own frame (`viasForPoses` over the sub-block's scoped block),
/// then offset each via by (dx, dy) so it lands under the staged parts. Net
/// names collapse the same way pad nets do. The writer de-dups by position.
fn emitBlockVias(d: *DiffContext, w: anytype, first: *bool, block: *const env_mod.DesignBlock, poses: []const pcb_layout.RefPose, dx: f64, dy: f64) !void {
    // Module-local frame — the parent board's drawn outline doesn't apply here.
    const vias = pcb_layout.viasForPoses(d.spc.arena, block, d.spc.project_dir, .{ .poses = poses, .outline = .authored_only }, .{}) orelse return;
    for (vias) |v| {
        const net = bareNetName(maybeCollapseDotSubNet(v.net, d.dot_nets));
        if (net.len == 0) continue;
        if (!first.*) try w.writeAll(",");
        first.* = false;
        try w.writeAll(add_via_op_open);
        try json_writer.writeString(w, net);
        try w.print(via_coords_fmt, .{
            mmToNm(v.x + dx), mmToNm(v.y + dy), mmToNm(v.dia), mmToNm(v.drill),
        });
        d.summary.vias += 1;
    }
}

/// The sub-block named `name`, or null when none matches (e.g. a design-`section`
/// part rather than a `(sub-block …)`).
fn subBlockNamed(sub_blocks: []const env_mod.SubBlock, name: []const u8) ?env_mod.SubBlock {
    for (sub_blocks) |sb| {
        if (std.mem.eql(u8, sb.name, name)) return sb;
    }
    return null;
}

/// Strip a leading `"<sec>/"` from a flattened ref-des, giving the module-local
/// ref the module layout is keyed by (`"buck_3v3d/R28"`, `"buck_3v3d"` → `"R28"`).
/// Returns `ref` unchanged when the prefix doesn't match.
fn stripSubPrefix(ref: []const u8, sec: []const u8) []const u8 {
    if (ref.len > sec.len + 1 and std.mem.startsWith(u8, ref, sec) and ref[sec.len] == '/')
        return ref[sec.len + 1 ..];
    return ref;
}

/// Emit `add_via` ops for the **computed** GND-plane stitching vias of a
/// first-insertion seed — a fresh `router.groundVias` pass over the layout's
/// poses, not copper anyone saved. Fires when vias weren't opted out
/// (`?no_layout_vias=1`) and this sync reproduced the whole saved layout
/// (`seedsWholeLayout`). That all-named gate matters because `loadSyncVias`
/// rebuilds the *whole* placement at the layout poses; a part the layout doesn't
/// name would sit at the origin there and drop a stray via, so we skip vias
/// entirely for a partial seed. The writer de-dups by position, so a later
/// re-seed of the same board re-emits these harmlessly, and a computed via
/// landing where the saved copper already has one (`emitLayoutCopper`) collapses
/// into it. Net names are collapsed the same way pad nets are, so the via lands
/// on the GND the pads reference.
fn emitLayoutVias(
    d: *DiffContext,
    block: *const env_mod.DesignBlock,
    project_dir: []const u8,
    name: []const u8,
    parsed: ParsedSyncPlan,
    w: anytype,
    first: *bool,
) !void {
    if (!parsed.seed.layout_vias) return;
    if (!seedsWholeLayout(d)) return;
    const vias = pcb_layout.loadSyncVias(d.spc.arena, block, project_dir, name) orelse return;
    for (vias) |v| {
        const net = bareNetName(maybeCollapseDotSubNet(v.net, parsed.dot_nets));
        if (net.len == 0) continue;
        if (!first.*) try w.writeAll(",");
        first.* = false;
        try w.writeAll(add_via_op_open);
        try json_writer.writeString(w, net);
        try w.print(via_coords_fmt, .{
            mmToNm(v.x), mmToNm(v.y), mmToNm(v.dia), mmToNm(v.drill),
        });
        d.summary.vias += 1;
    }
}

/// Seed the DSL-authored edge mask opening into a new KiCad board as closed
/// F.Mask and B.Mask graphic strokes. The stroke is centred on Edge.Cuts, so a
/// width of `2*mask-width` exposes exactly the authored band inside the board.
/// Board graphics are emitted only on first insertion: the board snapshot has
/// no update identity for existing graphics, so repeating them would stack
/// duplicates.
fn emitPerimeterMask(
    d: *DiffContext,
    block: *const env_mod.DesignBlock,
    project_dir: []const u8,
    name: []const u8,
    w: anytype,
    first: *bool,
) !void {
    if (!d.board_fresh or !seedsWholeLayout(d)) return;
    const mask = pcb_layout.loadSyncPerimeterMask(d.spc.arena, block, project_dir, name) orelse return;
    const layers = [_][]const u8{ proto_layer_f_mask, proto_layer_b_mask };
    for (layers) |layer| {
        for (mask.outline, 0..) |a, i| {
            const b = mask.outline[(i + 1) % mask.outline.len];
            if (!first.*) try w.writeAll(",");
            first.* = false;
            try w.writeAll(board_item_op_open);
            var item_first = true;
            try writeBoardShapeOpen(w, layer, 2 * mask.width, &item_first);
            try writeSegmentGeom(w, a[0], a[1], b[0], b[1]);
            try w.writeAll("}}}");
        }
    }
}

/// Emit the saved layout's OWN routed copper — the tracks and vias the board was
/// actually routed with, which the sync used to drop on the floor entirely: a
/// first-insertion seed reproduced the placement and then had to have its routing
/// pasted into the `.kicad_pcb` by hand. The track twin of `emitLayoutVias`, and
/// gated identically (`seedsWholeLayout`) — copper only means anything when every
/// footprint under it landed at the pose it was routed at — with tracks and vias
/// separately opt-out-able (`?no_layout_tracks=1` / `?no_layout_vias=1`).
///
/// Copper is emitted UNTRANSFORMED: unlike `emitSeedCopper` (which offsets a
/// module's copper into the staging band) these are whole-design board
/// coordinates and the footprints went down at exactly the same poses, so any
/// transform here would shear the copper off its pads.
///
/// A track's net is resolved through `net_display` — the same map that spelled
/// every pad net this sync wrote — so a saved `amp1/AMP_IN` track joins the pads
/// the diff put on `amp1/AMP_IN` rather than splitting the net onto a bare
/// `AMP_IN`. Copper on a net the design no longer has is skipped rather than
/// guessed at: a wrong net name is silently-wrong copper, which is worse than
/// absent copper the user can see is missing.
fn emitLayoutCopper(
    d: *DiffContext,
    project_dir: []const u8,
    name: []const u8,
    w: anytype,
    first: *bool,
) !void {
    if (!d.seed.layout_tracks and !d.seed.layout_vias) return;
    if (!seedsWholeLayout(d)) return;
    const routes = pcb_layout.loadSyncRoutes(d.spc.arena, project_dir, name) orelse return;
    if (d.seed.layout_tracks) {
        for (routes.tracks) |t| {
            const net = d.net_display.get(t.net) orelse continue;
            if (net.len == 0) continue;
            // The SAVED width wins here, unlike `emitSeedCopper`: that path
            // re-targets a module's copper onto a parent board whose net classes
            // may differ, while this copper is the design's own, drawn at its own
            // widths. The class rule only fills in for a sidecar that stored none.
            const width = if (t.w > 0) t.w else seedNetRule(d, net).width;
            if (width <= 0) continue;
            const layer = try kicadCopperLayer(d.spc.arena, t.l);
            if (!first.*) try w.writeAll(",");
            first.* = false;
            const mid: ?[2]f64 = if (t.xm) |xm| if (t.ym) |ym| .{ xm, ym } else null else null;
            try w.writeAll(if (mid != null) add_arc_op_open else add_track_op_open);
            try json_writer.writeString(w, net);
            if (mid) |m| {
                try w.print(",\"x1\":{d},\"y1\":{d},\"xm\":{d},\"ym\":{d},\"x2\":{d},\"y2\":{d},\"width\":{d},\"layer\":", .{
                    mmToNm(t.x1), mmToNm(t.y1), mmToNm(m[0]),  mmToNm(m[1]),
                    mmToNm(t.x2), mmToNm(t.y2), mmToNm(width),
                });
            } else {
                try w.print(track_coords_fmt, .{
                    mmToNm(t.x1),  mmToNm(t.y1),
                    mmToNm(t.x2),  mmToNm(t.y2),
                    mmToNm(width),
                });
            }
            try json_writer.writeString(w, layer);
            try w.writeAll("}");
            d.summary.tracks += 1;
        }
    }
    if (!d.seed.layout_vias) return;
    for (routes.vias) |v| {
        const net = d.net_display.get(v.net) orelse continue;
        if (net.len == 0) continue;
        // Same rule as the tracks: saved geometry first, class rule as the
        // fallback for a sidecar that stored none (an older or imported one).
        const rule = seedNetRule(d, net);
        const dia = if (v.d > 0) v.d else rule.via_dia;
        const drill = if (v.drill > 0) v.drill else rule.via_drill;
        if (dia <= 0 or drill <= 0) continue;
        if (!first.*) try w.writeAll(",");
        first.* = false;
        try w.writeAll(add_via_op_open);
        try json_writer.writeString(w, net);
        try w.print(via_coords_fmt, .{
            mmToNm(v.x), mmToNm(v.y), mmToNm(dia), mmToNm(drill),
        });
        d.summary.vias += 1;
    }
}

/// Emit the destructive half of an explicit PCB-editor → KiCad handoff. The
/// writer removes existing tracks, vias, Edge.Cuts, and stale groups, then
/// appends this named layout's saved copper and finished outline. Footprints,
/// zones, board setup/rules, and unrelated graphics remain in the KiCad file.
/// Placement ops were emitted per matched footprint in `handleMatched`, before
/// each forced geometry refresh, so pad orientation follows the new pose.
fn emitAuthoritativeLayout(
    d: *DiffContext,
    w: anytype,
    first: *bool,
) !void {
    const layout = d.authoritative_layout orelse return;
    if (!first.*) try w.writeAll(",");
    first.* = false;
    try w.writeAll("{\"op\":\"replace_layout\"}");

    if (layout.routes) |routes| {
        for (routes.tracks) |t| {
            const net = d.net_display.get(t.net) orelse continue;
            if (net.len == 0 or t.w <= 0) continue;
            if (!first.*) try w.writeAll(",");
            first.* = false;
            const mid: ?[2]f64 = if (t.xm) |xm| if (t.ym) |ym| .{ xm, ym } else null else null;
            try w.writeAll(if (mid != null) add_arc_op_open else add_track_op_open);
            try json_writer.writeString(w, net);
            if (mid) |m| {
                try w.print(",\"x1\":{d},\"y1\":{d},\"xm\":{d},\"ym\":{d},\"x2\":{d},\"y2\":{d},\"width\":{d},\"layer\":", .{
                    mmToNm(t.x1), mmToNm(t.y1), mmToNm(m[0]), mmToNm(m[1]),
                    mmToNm(t.x2), mmToNm(t.y2), mmToNm(t.w),
                });
            } else {
                try w.print(track_coords_fmt, .{
                    mmToNm(t.x1), mmToNm(t.y1), mmToNm(t.x2), mmToNm(t.y2), mmToNm(t.w),
                });
            }
            try json_writer.writeString(w, try kicadCopperLayer(d.spc.arena, t.l));
            try w.writeAll("}");
            d.summary.tracks += 1;
        }
        for (routes.vias) |v| {
            const net = d.net_display.get(v.net) orelse continue;
            if (net.len == 0 or v.d <= 0 or v.drill <= 0) continue;
            if (!first.*) try w.writeAll(",");
            first.* = false;
            try w.writeAll(add_via_op_open);
            try json_writer.writeString(w, net);
            if (std.mem.eql(u8, net, "GND") and !savedViaTouchesTrack(v, routes.tracks)) {
                try w.print(free_via_coords_fmt, .{ mmToNm(v.x), mmToNm(v.y), mmToNm(v.d), mmToNm(v.drill) });
            } else {
                try w.print(via_coords_fmt, .{ mmToNm(v.x), mmToNm(v.y), mmToNm(v.d), mmToNm(v.drill) });
            }
            d.summary.vias += 1;
        }
    }

    // Keep board-level text and copper pours in the KiCad handoff. These are
    // the board-level objects the native Gerber writer also emits.
    try emitAuthoritativeTexts(w, first, layout.texts);
    try emitAuthoritativeZones(d, w, first, layout);

    if (layout.outline.len >= 3) {
        for (layout.outline, 0..) |a, i| {
            const b = layout.outline[(i + 1) % layout.outline.len];
            if (a[0] == b[0] and a[1] == b[1]) continue;
            var belongs_to_arc = false;
            for (layout.outline_arcs) |arc| {
                if (outline_mod.arcOwnsSegment(arc, a, b, 0.0001)) {
                    belongs_to_arc = true;
                    break;
                }
            }
            if (belongs_to_arc) continue;
            if (!first.*) try w.writeAll(",");
            first.* = false;
            try w.print(
                "{{\"op\":\"add_outline\",\"x1\":{d},\"y1\":{d},\"x2\":{d},\"y2\":{d}}}",
                .{ mmToNm(a[0]), mmToNm(a[1]), mmToNm(b[0]), mmToNm(b[1]) },
            );
            d.summary.outline_edges += 1;
        }
        for (layout.outline_arcs) |arc| {
            if (!first.*) try w.writeAll(",");
            first.* = false;
            try w.print(
                "{{\"op\":\"add_outline_arc\",\"x1\":{d},\"y1\":{d},\"xm\":{d},\"ym\":{d},\"x2\":{d},\"y2\":{d}}}",
                .{ mmToNm(arc.p1[0]), mmToNm(arc.p1[1]), mmToNm(arc.pm[0]), mmToNm(arc.pm[1]), mmToNm(arc.p2[0]), mmToNm(arc.p2[1]) },
            );
            d.summary.outline_edges += 1;
        }
    }
    const saved_zones: usize = if (layout.routes) |routes| routes.zones.len else 0;
    const exported_zones = if (layout.planes.len > 0) layout.planes.len + saved_zones else layout.zones;
    d.summary.layout_zones = @intCast(@min(exported_zones, @as(usize, std.math.maxInt(u32))));
}

/// KiCad's `free` marker belongs only on a stitching barrel with no routed
/// copper attached. Marking every GND via free makes pcbnew stop using the
/// track-attached barrels to join filled zones across layers, which turns a
/// connected multi-layer ground pour into a zone-to-itself airwire.
fn savedViaTouchesTrack(via: pcb_layout.SavedVia, tracks: []const pcb_layout.SavedTrack) bool {
    for (tracks) |track| {
        if (!std.mem.eql(u8, via.net, track.net)) continue;
        const dx = track.x2 - track.x1;
        const dy = track.y2 - track.y1;
        const length_sq = dx * dx + dy * dy;
        const along = if (length_sq > 0)
            std.math.clamp(((via.x - track.x1) * dx + (via.y - track.y1) * dy) / length_sq, 0, 1)
        else
            0;
        const nearest_x = track.x1 + along * dx;
        const nearest_y = track.y1 + along * dy;
        const reach = via.d / 2 + track.w / 2 + via_track_contact_eps;
        if (std.math.hypot(via.x - nearest_x, via.y - nearest_y) <= reach) return true;
    }
    return false;
}

