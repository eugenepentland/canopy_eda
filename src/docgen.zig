}

fn renderDatasheetReview(writer: anytype) !void {
    try writer.writeAll(
        \\
        \\## Datasheet review preflight
        \\
        \\A component declares the datasheets that document it with one
        \\`(datasheet "…")` field per PDF, directly inside its
        \\`lib/components/<name>.sexp` definition:
        \\
        \\```lisp
        \\(component lm66100
        \\  (footprint sc70-6)
        \\  (datasheet "LM66100DCKR.pdf"))
        \\```
        \\
        \\The value is either a filename in `lib/datasheets/` or an absolute
        \\`http(s)` URL (for a PDF that may not be redistributed). This one
        \\field is what fills each placed instance's `docs.datasheets`, what
        \\`describe_component` reports under `datasheets`, what a
        \\`(datasheet-review …)` record must name, and what the datasheet
        \\coverage check requires of every active IC — a PDF sitting in
        \\`lib/datasheets/` that no component declares documents nothing. The
        \\whole chain has CLI tools: `fetch_datasheet` (URL → the PDF on disk),
        \\`attach_datasheet` (PDF → this declaration), `read_datasheet` (text +
        \\the `sha256` to cite below).
        \\
        \\Active-component library records may bind their requirement review
        \\to an exact PDF using `(datasheet-review …)`. `read_datasheet`
        \\returns the current PDF `sha256`; replacing that file automatically
        \\makes the review stale. A complete record has this shape:
        \\
        \\```lisp
        \\(datasheet-review
        \\  (datasheet "part.pdf")
        \\  (sha256 "<64 lowercase hex characters>")
        \\  (status complete)
        \\  (reviewed-by "agent-or-human")
        \\  (date "YYYY-MM-DD")
        \\  (category supply)
        \\  (category-na sequencing "reason this topic is not applicable"))
        \\```
        \\
        \\Every component requirement must cite that PDF with a 1-based page
        \\and a short source quote. `netlisp check --profile preflight` and CLI
        \\`run_checks {profile:"preflight"}` gate incomplete reviews and
        \\unverified manual requirements. Authoring mode reports those legacy
        \\gaps as warnings. `--profile release` is preflight plus the
        \\component-class profile obligations (`profile_incomplete` findings:
        \\supply pins without voltage-range and decoupling checks or current
        \\annotations, control pins without `(electrical …)` thresholds, class
        \\review categories, missing `(thermal …)`, a loop or mixer class with no
        \\gated analysis form), at least one cited requirement on every active
        \\part, and the evaluator's own warnings (an unknown sub-form is an
        \\error). A component binds its class with `(class <key>)` — one of
        \\`ldo`, `switching-regulator`, `protection`, `load-switch`, `mcu`,
        \\`level-shifter`, `pll-loop`, `integrated-synthesizer`,
        \\`clock-jitter-cleaner`, `crystal-oscillator`, `rf-amplifier`, `mixer`,
        \\`rf-attenuator-switch`, `rf-passive`, `rf-detector`, `op-amp`, `sensor`,
        \\`connectors`, `power-path-passives` — else the class is inferred from
        \\its pin function names. Required review categories are:
    );
    try writer.writeAll(" ");
    for (preflight.required_review_categories, 0..) |category, index| {
        if (index > 0) try writer.writeAll(", ");
        try writer.print("`{s}`", .{category});
    }
    try writer.writeAll(". Each must use `(category KEY)` or a `(category-na KEY \"rationale\")`.\n");
}

/// Slice one `## `-headed section out of a rendered reference (heading
/// line through the byte before the next `## ` heading, or EOF). Matching
/// is case-insensitive on the heading title so CLI callers can ask for
/// "numeric literals". Returns null when no heading matches — derive the
/// valid titles with `SectionIterator`, never from a hardcoded list.
pub fn extractSection(doc: []const u8, title: []const u8) ?[]const u8 {
    var it = SectionIterator{ .doc = doc };
    while (it.next()) |sec| {
        if (std.ascii.eqlIgnoreCase(sec.title, title)) return sec.body;
    }
    return null;
}

/// One `## ` section of a rendered reference: the bare heading title and
/// the full body slice (heading line included).
pub const Section = struct { title: []const u8, body: []const u8 };

/// Walk the `## ` headings of a rendered reference in order. Keeps the
/// section list derived from the generated output itself, so a new doc
/// section is automatically addressable with zero registration.
pub const SectionIterator = struct {
    doc: []const u8,
    pos: usize = 0,

    pub fn next(self: *SectionIterator) ?Section {
        const start = findHeading(self.doc, self.pos) orelse return null;
        const title_start = start + "## ".len;
        const title_end = std.mem.indexOfScalarPos(u8, self.doc, title_start, '\n') orelse self.doc.len;
        const end = findHeading(self.doc, title_end) orelse self.doc.len;
        self.pos = end;
        return .{
            .title = std.mem.trim(u8, self.doc[title_start..title_end], " \r"),
            .body = self.doc[start..end],
        };
    }

    /// Byte offset of the next line starting with `## `, at or after `from`.
    fn findHeading(doc: []const u8, from: usize) ?usize {
        var i = from;
        while (std.mem.indexOfPos(u8, doc, i, "## ")) |hit| {
            if (hit == 0 or doc[hit - 1] == '\n') return hit;
            i = hit + 1;
        }
        return null;
    }
};

/// Write table-cell content, escaping `|` so syntax templates like
/// `(status concept|implemented|review)` don't split the Markdown cell.
fn writeCell(writer: anytype, text: []const u8) !void {
    for (text) |c| {
        if (c == '|') try writer.writeAll("\\|") else try writer.writeByte(c);
    }
}

fn writeArity(writer: anytype, schema: ?forms.FormSchema) !void {
    const s = schema orelse {
        try writer.writeAll("—");
        return;
    };
    if (s.max_args) |max| {
        if (max == s.min_args) {
            try writer.print("{d}", .{s.min_args});
        } else {
            try writer.print("{d}–{d}", .{ s.min_args, max });
        }
    } else {
        try writer.print("{d}+", .{s.min_args});
    }
}

/// Power-of-ten exponent of an SI multiplier (all entries in
/// `tokenizer.si_scales` are exact powers of ten).
fn multiplierExponent(m: f64) i32 {
    return numeric.checkedInt(i32, @round(@log10(m))) orelse 0;
}

