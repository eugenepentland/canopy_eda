//! Generator for `docs/language-forms.md` — the machine-checked reference
//! for the S-expression design language. Every section is rendered from a
//! table the implementation itself dispatches on, so the docs cannot
//! drift from the evaluator:
//!
//!   - `src/eval/forms.zig`          special forms, builtin operators,
//!                                   design-scope forms (+ arity schema)
//!   - `src/eval/fmt.zig`            `(fmt …)` directive table
//!   - `src/sexpr/tokenizer.zig`     SI numeric-literal suffix tables
//!   - `src/render_block_types.zig`  section-name classifier keywords
//!   - `src/eval/check_grammar.zig`  requirement-check grammar (`check_docs`,
//!                                   the same table `parseCheck` dispatches on)
//!   - `src/eval/thermal.zig`        the `(thermal …)` / `(power …)` grammar
//!                                   (`thermal_field_docs`, `power_form_doc`)
//!
//! Three enforcement layers keep it honest: `requireAllDocumented` in
//! forms.zig turns an undocumented form into a compile error; per-table
//! sync tests (e.g. fmt's directive-dispatch test) prove each table
//! matches its dispatch; and `zig build test` runs
//! `gen-language-docs --check` plus the drift test below, so a stale
//! committed file fails the build. Regenerate with `zig build docs`.

const std = @import("std");
const infra_fs = @import("infra/fs.zig");
const forms = @import("eval/forms.zig");
const fmt_mod = @import("eval/fmt.zig");
const tokenizer_mod = @import("sexpr/tokenizer.zig");
const block_types = @import("render_block_types.zig");
const check_grammar = @import("eval/check_grammar.zig");
const authored_rules = @import("eval/authored_rules.zig");
const thermal = @import("eval/thermal.zig");
const numeric = @import("numeric.zig");
const preflight = @import("preflight.zig");

/// Render the full Markdown reference. The output is deterministic — the
/// build's docs-check step and the drift test below compare it to the
/// checked-in `docs/language-forms.md`. Caller owns the returned slice.
pub fn renderLanguageReference(allocator: std.mem.Allocator) std.mem.Allocator.Error![]const u8 {
    var buf: std.Io.Writer.Allocating = .init(allocator);
    defer buf.deinit();
    renderTo(&buf.writer) catch return error.OutOfMemory;
    return buf.toOwnedSlice();
}

fn renderTo(writer: anytype) !void {
    try writer.writeAll(
        \\# S-Expression Language: Form Reference
        \\
        \\<!-- Auto-generated by src/docgen.zig from the evaluator's own
        \\     dispatch tables. Do not edit by hand — run `zig build docs`
        \\     to regenerate; `zig build test` fails when this file is stale. -->
        \\
        \\Every special form, builtin operator, fmt directive, numeric-literal
        \\suffix, and design-scope form the toolchain recognises, with arity
        \\contracts and one-line summaries. The hand-written prose lives in
        \\[`sexp-language.md`](sexp-language.md); this file is the
        \\machine-checked grammar surface.
        \\
        \\## Special forms
        \\
        \\Arguments are passed un-evaluated; each form decides what to evaluate.
        \\
        \\| Form | Arity | Summary |
        \\| --- | --- | --- |
        \\
    );
    for (forms.special_form_docs, 0..) |doc, i| {
        const variant: forms.SpecialForm = @fromBackingInt(@intCast(i));
        try writer.writeAll("| `");
        try writeCell(writer, doc.syntax);
        try writer.writeAll("` | ");
        try writeArity(writer, forms.schemaFor(variant));
        try writer.writeAll(" | ");
        try writeCell(writer, doc.summary);
        try writer.writeAll(" |\n");
    }

    try writer.writeAll(
        \\
        \\## Builtin operators
        \\
        \\Arithmetic, comparison, and logic operators. Arguments are evaluated left-to-right before the operator runs.
        \\
        \\| Form | Summary |
        \\| --- | --- |
        \\
    );
    for (forms.builtin_docs) |doc| {
        try writer.writeAll("| `");
        try writeCell(writer, doc.syntax);
        try writer.writeAll("` | ");
        try writeCell(writer, doc.summary);
        try writer.writeAll(" |\n");
    }

    try writer.writeAll(
        \\
        \\## String formatting directives
        \\
        \\Specifiers accepted in a `(fmt "template" args…)` template. Each
        \\consumes the next argument of the listed type (or none).
        \\
        \\| Directive | Argument | Summary |
        \\| --- | --- | --- |
        \\
    );
    for (fmt_mod.directives) |d| {
        try writer.print("| `~{c}` | {s} | {s} |\n", .{
            d.spec,
            switch (d.arg) {
                .value => "value",
                .number => "number",
                .string => "string",
                .none => "—",
            },
            d.summary,
        });
    }

    try writer.writeAll(
        \\
        \\## Numeric literals
        \\
        \\Bare numbers accept an SI scale suffix, optionally followed by one
        \\unit letter that carries no scale (`100nF` == `100n`); a unit
        \\letter may also stand alone (`3.3V` == `3.3`). The suffix must end
        \\the token — `100kHz` falls through to a plain atom. Dimension
        \\tokens are separate: `mm` keeps the value in millimetres and `mil`
        \\converts to mm (1 mil = 0.0254 mm).
        \\
        \\| Suffix | Scale | Notes |
        \\| --- | --- | --- |
        \\
    );
    for (tokenizer_mod.si_scales) |s| {
        try writer.print("| `{c}` | 10^{d} | {s} |\n", .{
            s.letter,
            multiplierExponent(s.multiplier),
            if (s.bare) "" else "Only with a unit letter (`100mV`) — bare `3m`, `mm`, `mil` keep their dimension meanings.",
        });
    }
    try writer.writeAll("\nUnit letters (scale-free): ");
    for (tokenizer_mod.si_unit_letters, 0..) |u, i| {
        if (i > 0) try writer.writeAll(", ");
        try writer.print("`{c}`", .{u});
    }
    try writer.writeAll(".\n");

    try renderScopeForms(writer);

    try renderSubFormSections(writer);

    try renderClassifierKeywords(writer);

    try renderReferenceAppendices(writer);
}

/// Render the "Design-scope forms" section from `forms.scope_form_docs`, the
/// same table the design-block / section dispatch switches on.
fn renderScopeForms(writer: anytype) !void {
    try writer.writeAll(
        \\
        \\## Design-scope forms
        \\
        \\Forms that may appear directly inside a `(design-block …)`, a
        \\`(section …)`, or a nested sub-section. The scope column lists
        \\where each is accepted: **D** = design-block top level,
        \\**S** = section, **s** = sub-section.
        \\
        \\| Form | Scope | Summary |
        \\| --- | --- | --- |
        \\
    );
    for (forms.scope_form_docs) |row| {
        try writer.writeAll("| `");
        try writeCell(writer, row.doc.syntax);
        try writer.writeAll("` | ");
        if (row.scope.design_block) try writer.writeAll("D") else try writer.writeAll("·");
        if (row.scope.section) try writer.writeAll("S") else try writer.writeAll("·");
        if (row.scope.sub_section) try writer.writeAll("s") else try writer.writeAll("·");
        try writer.writeAll(" | ");
        try writeCell(writer, row.doc.summary);
        try writer.writeAll(" |\n");
    }
}

/// Render one sub-form registry as a `| Form | Summary |` table. A row that
/// nests inside a sibling carries its parent in the syntax template, so the
/// nesting is visible without a second column.
fn renderSubFormTable(writer: anytype, table: []const forms.SubFormDoc) !void {
    try writer.writeAll("\n| Form | Summary |\n| --- | --- |\n");
    for (table) |row| {
        try writer.writeAll("| `");
        try writeCell(writer, row.syntax);
        try writer.writeAll("` | ");
        try writeCell(writer, row.summary);
        try writer.writeAll(" |\n");
    }
}

/// The compound forms whose bodies have their own grammar one level down.
/// Each section is rendered from the registry the evaluator derives its
/// accepted-children list from, so the two cannot drift.
fn renderSubFormSections(writer: anytype) !void {
    try renderInstanceSubForms(writer);
    try renderSubBlockSubForms(writer);
    try renderPortSubForms(writer);
    try renderMarkerForms(writer);
}

fn renderReferenceAppendices(writer: anytype) !void {
    try renderComponentFields(writer);
    try renderThermalForms(writer);
    try renderRequirementChecks(writer);
    try renderNetRulePredicates(writer);
    try renderDatasheetReview(writer);
}

/// Render the `(instance …)` and `(pins …)` body grammars — the two ways a
/// placed part's pins reach nets.
fn renderInstanceSubForms(writer: anytype) !void {
    try writer.writeAll(
        \\
        \\## Instance sub-forms
        \\
        \\The body of an `(instance "REF" component …)`. A bare string child is
        \\positional shorthand for the next physical pad (`(instance "R1"
        \\(res-0402 "10k") "VIN" "TAP")` wires pads 1 and 2), and any
        \\`(key "value")` child whose head is NOT one of the reserved forms
        \\below becomes an inline **property** override on the placed part —
        \\that is how `(mpn "…")`, `(class ldo)` and
        \\`(module-bypass "reason")` are written. A property child whose value
        \\is not a string is dropped with a warning.
        \\
        \\Rows written inside a sibling form show that nesting in their
        \\template.
        \\
    );
    try renderSubFormTable(writer, forms.instance_form_docs);
    try writer.writeAll(
        \\
        \\A `(pins "REF" …)` block wires an already-placed part out of line,
        \\usually one section down from where the instance is declared. Its
        \\children:
        \\
    );
    try renderSubFormTable(writer, forms.pins_form_docs);
}

/// Render the `(sub-block …)` body grammar — above all `(bridge …)`, the
/// form that wires a module's ports to board nets.
fn renderSubBlockSubForms(writer: anytype) !void {
    try writer.writeAll(
        \\
        \\## Sub-block sub-forms
        \\
        \\Children of a `(sub-block "name" (module-call …) …)`. Anything else
        \\is rejected with a warning rather than going silently dead.
        \\
        \\`(bridge …)` is how hierarchy is wired. Each bridged port `P` emits
        \\one net tie between board net `PREFIX<suffix>` and module net
        \\`<name>/P`, where `<suffix>` is `P` unless `(rename P SUFFIX)`
        \\overrides it. Two idioms are in use: a shared prefix for a peripheral
        \\bus (`(bridge "IMU_" SCK MOSI MISO (rename CS NCS))`), and an empty
        \\prefix with one `(rename PORT NET)` per port, which reads as a
        \\port-to-net map. Power and ground ports are normally left off the
        \\list — they stay wired through the consolidated `(net …)` rail forms.
        \\
    );
    try renderSubFormTable(writer, forms.sub_block_form_docs);
}

/// Render the `(port …)` option grammar.
fn renderPortSubForms(writer: anytype) !void {
    try writer.writeAll(
        \\
        \\## Port sub-forms
        \\
        \\Parenthesised options of a `(port …)` declaration, in any order after
        \\the direction. Bare-token options sit alongside them: `optional`
        \\marks the port as not required by the module contract, a
        \\signal-type keyword (`power`, `clock`, `rf`, …) sets the port kind,
        \\`role R` / `protocol P` / `class C` each consume the following token
        \\as metadata, and a bare number is the nominal voltage. An
        \\unrecognised option warns.
        \\
    );
    try renderSubFormTable(writer, forms.port_form_docs);
}

/// Render the identity/layout markers accepted in design scope.
fn renderMarkerForms(writer: anytype) !void {
    try writer.writeAll(
        \\
        \\## Identity and layout markers
        \\
        \\Head atoms accepted wherever design-scope forms are, carrying
        \\identity or layout intent rather than circuit content. They are inert
        \\in the scope dispatch — listed here so they never look like a typo
        \\and never draw an unknown-sub-form warning.
        \\
    );
    try renderSubFormTable(writer, forms.marker_form_docs);
}

/// Render the `(component …)` / `(component-family …)` library-definition
/// fields from the same registry `eval/modules.zig` skips over.
fn renderComponentFields(writer: anytype) !void {
    try writer.writeAll(
        \\
        \\## Component library fields
        \\
        \\The body of a `lib/components/<name>.sexp` definition. A
        \\`(component …)` is a fixed part; a `(component-family …)` is
        \\parameterised by one `(parameter …)` the call site supplies, as in
        \\`(cap-0402 "100nF")`. Any other `(key "value")` child is an inline
        \\**property** carried onto every placed instance — `(class ldo)`,
        \\`(mpn "…")` and `(manufacturer "…")` are all properties, not fields.
        \\
    );
    try renderSubFormTable(writer, forms.component_form_docs);
}

/// Render the "Section-name classifier keywords" section from the
/// `render_block_types` name-rule table and the `Category` enum.
fn renderClassifierKeywords(writer: anytype) !void {
    try writer.writeAll(
        \\
        \\## Section-name classifier keywords
        \\
        \\The system-overview SVG picks each section's column + colour by
        \\case-insensitive keyword match on the section **name**, walking
        \\these rules in priority order (first hit wins). A section matching
        \\no rule falls back to **connector** when it contains a J/P-prefixed
        \\instance, else **peripheral**. An explicit `(category <key>)`
        \\declaration overrides the heuristic.
        \\
        \\| Category | Name keywords |
        \\| --- | --- |
        \\
    );
    for (block_types.name_rules) |rule| {
        try writer.print("| {s} | ", .{@tagName(rule.category)});
        for (rule.keywords, 0..) |kw, i| {
            if (i > 0) try writer.writeAll(", ");
            try writer.print("`{s}`", .{kw});
        }
        try writer.writeAll(" |\n");
    }
    try writer.writeAll("\nValid `(category <key>)` keys: ");
    for (std.enums.values(block_types.Category), 0..) |cat, i| {
        if (i > 0) try writer.writeAll(", ");
        try writer.print("`{s}`", .{@tagName(cat)});
    }
    try writer.writeAll(".\n");
}

/// Render the "Thermal declarations" section from the tables `eval/thermal.zig`
/// parses with: the library `(thermal …)` sub-forms and the instance-scope
/// `(power …)` form.
fn renderThermalForms(writer: anytype) !void {
    try writer.writeAll(
        \\
        \\## Thermal declarations
        \\
        \\What a part can take, and what it burns — the two inputs to the
        \\screening thermal analysis (`Tj = Ta + P·θJA`, lumped, no layout
        \\coupling). A library part declares its envelope with `(thermal …)`
        \\inside its `(component …)` / `(component-family …)` body; an
        \\instance declares its dissipation with `(power …)` in its own body.
        \\Both are optional: a part with no `(thermal (theta-ja …))` is
        \\screened against a package estimate, and a part with no `(power …)`
        \\has its dissipation derived from annotated pin currents or, for a
        \\regulator module, from its back-computed conversion loss.
        \\
        \\| Form | Summary |
        \\| --- | --- |
        \\
    );
    for (thermal.thermal_field_docs) |doc| {
        try writer.writeAll("| `");
        try writeCell(writer, doc.syntax);
        try writer.writeAll("` | ");
        try writeCell(writer, doc.summary);
        try writer.writeAll(" |\n");
    }
    try writer.writeAll("| `");
    try writeCell(writer, thermal.power_form_doc.syntax);
    try writer.writeAll("` | ");
    try writeCell(writer, thermal.power_form_doc.summary);
    try writer.writeAll(" |\n");
}

/// Render the "Requirement checks" section from `check_grammar.check_docs` —
/// the same table `parseCheck` dispatches on, so the documented grammar can
/// never drift from the checker.
fn renderRequirementChecks(writer: anytype) !void {
    try writer.writeAll(
        \\
        \\## Requirement checks
        \\
        \\Machine-checkable rules that hang off a library
        \\`(requirement "text" (check …))` form — the executable half of a
        \\datasheet rule. Each is evaluated per placement of the part against
        \\its **containing block** (a sub-block's check sees the sub-block's
