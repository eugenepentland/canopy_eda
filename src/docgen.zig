        \\
        \\| Check form | Asserts (against the containing block) |
        \\| --- | --- |
        \\
    );
    for (check_grammar.check_docs) |d| {
        try writer.writeAll("| `");
        try writeCell(writer, d.syntax);
        try writer.writeAll("` | ");
        try writeCell(writer, d.summary);
        try writer.writeAll(" |\n");
    }
}

